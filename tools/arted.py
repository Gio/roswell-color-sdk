def glyph_block(f, g, cols):
    """Glyph g as colors, w*8 x h*8, row by row."""
    w, h = f['size']
    W, out = w * 8, [EMPTY] * (w * 8 * h * 8)
    for k in range(w * h):
        t = f['tiles'][g * w * h + k] if g * w * h + k < len(f['tiles']) else None
        tp = tile_px(t, 0, cols) if t is not None else [MISSING] * 64
        ox, oy = (k % w) * 8, (k // w) * 8
        for y in range(8):
            out[(oy + y) * W + ox:(oy + y) * W + ox + 8] = tp[y * 8:y * 8 + 8]
    return out


def render_text(f, text, cols):
    """text drawn in font f the way the game would look glyphs up: (w, h, pixels)."""
    lines = text.split('\n')
    gw, gh = f['size'][0] * 8, f['size'][1] * 8
    W, H = max(1, max(len(s) for s in lines)) * gw, len(lines) * gh
    px, blocks = [EMPTY] * (W * H), {}
    for ly, s in enumerate(lines):
        for cx, ch in enumerate(s):
            g = glyph_of(f, ch)
            b = blocks.get(g) or blocks.setdefault(g, glyph_block(f, g, cols))
            for y in range(gh):
                o = (ly * gh + y) * W + cx * gw
                px[o:o + gw] = b[y * gw:(y + 1) * gw]
    return W, H, px


class GlyphSheet(ttk.Frame):
    """A font's glyphs in a scrolling grid, each under its character; click selects one."""
    GAP = 5     # art pixels above a glyph for its character

    def __init__(self, master, app, on_select):
        super().__init__(master)
        self.app, self.on_select, self.z = app, on_select, app.z(3)
        f, self.cv = scrolled(self)
        f.pack(fill='both', expand=True)
        self.cv.configure(width=16 * 9 * self.z, height=8 * (8 + self.GAP) * self.z)
        self.cv.bind('<Button-1>', self.click)
        self.cv.bind('<Motion>', self.hover)
        self.font, self.cols, self.sel, self.zi = None, [EMPTY] * 4, -1, None

    def geometry(self):
        """(glyphs a row, cell w, cell h) in art pixels."""
        w, h = self.font['size']
        return max(1, 16 // w), w * 8 + 1, h * 8 + self.GAP

    def set(self, font, cols):
        self.font, self.cols = font, cols
        self.redraw()

    def redraw(self):
        f, z = self.font, self.z
        per, cw, chh = self.geometry()
        n = len(f['chars'])
        W, H = per * cw, max(1, -(-n // per)) * chh
        self.zi = ZImage(W, H, z, [EMPTY] * (W * H))
        cv = self.cv
        cv.delete('all')
        cv.create_image(0, 0, anchor='nw', image=self.zi.img)
        for g, ch in enumerate(f['chars']):
            x, y = (g % per) * cw, (g // per) * chh
            cv.create_text((x + cw / 2) * z, (y + self.GAP / 2) * z + 1, text=chars_text(ch), fill='#d8d8e0',
                           font=('TkDefaultFont', max(7, z * 2)))
            self.update_glyph(g)
        cv.configure(scrollregion=(0, 0, W * z, H * z))
        self.draw_sel()

    def update_glyph(self, g):
        if self.zi and 0 <= g < len(self.font['chars']):
            per, cw, chh = self.geometry()
            w, h = self.font['size']
            self.zi.put((g % per) * cw, (g // per) * chh + self.GAP, w * 8, h * 8, glyph_block(self.font, g, self.cols))

    def draw_sel(self):
        self.cv.delete('sel')
        if 0 <= self.sel < len(self.font['chars']):
            per, cw, chh = self.geometry()
            z, x, y = self.z, (self.sel % per) * cw, (self.sel // per) * chh
            self.cv.create_rectangle(x * z, y * z, (x + cw - 1) * z, (y + chh) * z, outline=SEL,
                                     width=max(2, self.app.z(2)), tags='sel')

    def select(self, g):
        n = len(self.font['chars'])
        self.sel = max(0, min(g, n - 1)) if n else -1
        self.draw_sel()
        self.on_select(self.sel)

    def glyph_at(self, e):
        per, cw, chh = self.geometry()
        x, y = int(self.cv.canvasx(e.x)) // (cw * self.z), int(self.cv.canvasy(e.y)) // (chh * self.z)
        g = y * per + x
        return g if 0 <= x < per and 0 <= g < len(self.font['chars']) else None

    def click(self, e):
        self.cv.focus_set()
        g = self.glyph_at(e)
        if g is not None:
            self.select(g)

    def hover(self, e):
        g = self.glyph_at(e)
        if g is not None:
            ch = self.font['chars'][g]
            self.app.status('glyph %d: %s  (U+%04X, "\\x%02x" in C)' % (g, char_name(ch), ord(ch), ord(ch)))


