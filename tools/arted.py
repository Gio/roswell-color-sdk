def pal_cols(proj, name):
    return [shown(h) for h in proj.palette(name)['colors']]


def spr_cols(base, k):
    """Colors of a sprite tile's values 0..3 in sprite palette k: 0 is transparent (None)."""
    return [None] + [base[s] for s in SUBSETS[k & 3]]


def contrast(c):
    r, g, b = (int(c[i:i + 2], 16) for i in (1, 3, 5))
    return '#000000' if r * 299 + g * 587 + b * 114 > 140000 else '#ffffff'


def tile_px(tile, attr, cols):
    out = []
    for y in range(8):
        for x in range(8):
            c = cols[tpx(tile, attr, x, y)]
            out.append(CHK[(x + y) & 1] if c is None else c)
    return out


def cell_px(c, tiles, cols):
    return tile_px(tiles[c[0]], c[1], cols) if 0 <= c[0] < len(tiles) else [MISSING] * 64


def render_map(rows, tiles, cols):
    h = len(rows)
    w = len(rows[0]) if h else 0
    W = w * 8
    px = [EMPTY] * (W * h * 8)
    for cy, row in enumerate(rows):
        for cx, c in enumerate(row):
            cp = cell_px(c, tiles, cols)
            for y in range(8):
                o = (cy * 8 + y) * W + cx * 8
                px[o:o + 8] = cp[y * 8:y * 8 + 8]
    return W, h * 8, px


def sprite_bounds(s, frames=None):
    """(x0, y0, x1, y1) around the box and every part, from the draw origin."""
    bw, bh, bx, by = s['box']
    x0, y0, x1, y1 = bx, by, bx + bw, by + bh
    for fr in (s['frames'] if frames is None else frames):
        for p in fr:
            x0, y0, x1, y1 = min(x0, p[0]), min(y0, p[1]), max(x1, p[0] + 8), max(y1, p[1] + 8)
    return x0, y0, max(x1, x0 + 8), max(y1, y0 + 8)


def render_sprite(frame, tiles, base, x0, y0, w, h):
    px = [CHK[(((x0 + x) >> 2) + ((y0 + y) >> 2)) & 1] for y in range(h) for x in range(w)]
    for p in reversed(frame):  # earlier parts are on top
        if not 0 <= p[2] < len(tiles):
            continue
        cols, tile, ox, oy = spr_cols(base, p[3]), tiles[p[2]], p[0] - x0, p[1] - y0
        for y in range(8):
            if 0 <= oy + y < h:
                for x in range(8):
                    if 0 <= ox + x < w:
                        c = cols[tpx(tile, p[3], x, y)]
                        if c is not None:
                            px[(oy + y) * w + ox + x] = c
    return px


def line(a, b):
    """The points from a to b, for strokes that move faster than the mouse reports."""
    (x0, y0), (x1, y1) = a, b
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx, sy = (1 if x1 > x0 else -1), (1 if y1 > y0 else -1)
    err, out = dx + dy, []
    while True:
        out.append((x0, y0))
        if (x0, y0) == (x1, y1):
            return out
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy


class ZImage:
    """A PhotoImage of w x h art pixels shown z times bigger, which can be updated a block at a time."""

    def __init__(self, w, h, z, px):
        self.w, self.h, self.z = w, h, z
        small = tk.PhotoImage(width=max(w, 1), height=max(h, 1))
        if w and h:
            small.put(' '.join('{%s}' % ' '.join(px[y * w:(y + 1) * w]) for y in range(h)))
        self.img = small.zoom(z) if z > 1 else small

    def put(self, x, y, w, h, px):
        z, rows = self.z, []
        for j in range(h):
            row = '{%s}' % ' '.join(c for c in px[j * w:(j + 1) * w] for _ in range(z))
            rows += [row] * z
        self.img.put(' '.join(rows), to=(x * z, y * z))


