class History:
    """Undo by snapshots. Before a change, checkpoint() copies the documents it touches (a font, a
    group, a picture, the palettes, or the fonts, groups or pictures list); undo puts the copies back in place."""
    LIMIT = 400

    def __init__(self, app):
        self.app, self.undo, self.redo, self.last = app, [], [], 0.0

    def _snap(self, objs):
        shallow = (self.app.proj.pictures, self.app.proj.groups, self.app.proj.fonts)
        return [(o, list(o) if any(o is s for s in shallow) else copy.deepcopy(o)) for o in objs]

    def checkpoint(self, *objs, merge=None):
        """merge: a key; checkpoints with the same key less than 1.5 s apart are one undo step."""
        now = time.monotonic()
        if merge is not None and self.undo and self.undo[-1][0] == merge and now - self.last < 1.5:
            self.last = now
            self.app.changed()
            return
        self.undo.append((merge, self._snap(objs)))
        del self.undo[:-self.LIMIT]
        self.redo.clear()
        self.last = now
        self.app.changed()

    def step(self, src, dst):
        if not src:
            return False
        _, snaps = src.pop()
        dst.append((None, self._snap([o for o, _ in snaps])))
        for o, c in snaps:
            if isinstance(o, dict):
                o.clear()
                o.update(c)
            else:
                o[:] = c
        self.last = 0.0
        return True

    def clear(self):
        self.undo.clear()
        self.redo.clear()


