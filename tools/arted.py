#!/usr/bin/env python3
"""arted: a folder of game art (an art project) - the editor, and the export to Roswell Color C data.

The art project is the source of the game's art: this edits, checks and exports it. This repo's is assets/,
which tools/artx.js imported once from old-spook. Standard library only (tkinter for the editor).

    python tools/arted.py [art dir]                        the editor
    python tools/arted.py export <art dir> [C out dir]     export to C       default C out dir: the project's
    python tools/arted.py check <art dir>                  list the problems that would stop an export
    python tools/arted.py new <art dir> [C out dir]        make a blank art project there

The editor opens the art project in the folder given; with none, a window asks for the folder (typed, or
picked with Browse), starting from the current folder. A folder that does not exist yet is made, with a
blank art project in it; File > Open folder switches to another. Each project keeps the folder it exports
to in art.json ("export", relative to the project; a new one exports to src/art beside it). File > Export
folder changes it; a C out dir given to `export` is used for that run only. File > Save writes the
project and File > Export C writes the C, the way `export` does.
Help > Keys lists the mouse and keyboard controls. export and check need no display or Tk.

The layout of an art project (all JSON):
  art.json        {"fonts": [names], "groups": [names, in export order], "pictures": [ids, in ART_PICTURES order],
                   "export": the folder Export C writes, relative to this one}
  palettes.json   {"palettes": [{"name", "colors": 4 x "#rrggbb", shade 0..3}]}
                  Exported as rc_color (5 bits a channel), so close colors may come out the same.
  fonts/<f>.json  {"name", "preview", "size": [w, h], "chars", "fallback", "tiles": [tile]}
                  A glyph is w x h tiles (1..4 each), one glyph per character of chars, in that order.
                  Glyph g is tiles g*w*h .. g*w*h + w*h - 1, row by row. chars are Latin-1 (U+0001..U+00FF,
                  one byte each in C); a character the font lacks is drawn with the fallback's glyph.
                  Exported as ART_FONT_<NAME>_*; ART_FONT_TILES, ART_FONT_GLYPH, ... name the first font.
  groups/<g>.json {"name", "desc", "preview",
                   "sprite_tiles": [tile], "sprites": [sprite],
                   "bg_tiles": [tile], "metatiles": [metatile]}
  pictures/<id>.json {"id", "name", "when", "preview", "tiles": [tile], "map": rows of [tile, attr]}

  tile      8 strings of 8 digits, a pixel each: 0..3. In a background tile that is the palette color;
            in a sprite tile 0 is transparent and 1..3 are the sprite palette's 3 colors.
  sprite    {"name", "label"?, "box": [w, h, x, y], "frames": [[part]]}
            part = [dx, dy, tile, attr]: an 8x8 hardware sprite at (dx, dy) from the draw origin.
            Earlier parts are drawn on top. box is the bounding box (x, y from the origin).
  metatile  {"name", "speed", "frames": [[4 x [tile, attr]]]}: 16x16, cells TL, TR, BL, BR.
  attr      palette number in bits 0..2, 0x20 flip X, 0x40 flip Y, 0x80 priority (map) / behind (sprite).
            Tile numbers run 0..511 across both slots; the export sets the slot 1 bit (0x08) itself.
  preview   the palette the editor shows this art in. The export ignores it.

Sprite palettes: palette k of ART_PAL_<NAME>_SPR is the 4 shades minus shade k, so a sprite tile's
value v in a part with palette k shows shade SUBSETS[k][v - 1].
"""
