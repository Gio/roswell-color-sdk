    def z(self, n):
        return max(1, int(n * self.S + 0.5))

    def make_menu(self):
        m = tk.Menu(self.root)
        f = tk.Menu(m, tearoff=0)
        f.add_command(label='Open folder...', accelerator='Ctrl+O', command=self.open_folder)
