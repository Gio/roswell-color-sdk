def export(proj, out=None):
    """Checks the project and writes the C files to out (default: the project's export folder). Returns
    (problems, files written, stale files removed); with problems nothing is written."""
    bad = check(proj)
    if bad:
        return bad, [], []
    out = Path(out) if out else proj.export_dir()
    out.mkdir(parents=True, exist_ok=True)
    files = export_files(proj, source_name(proj.root, out))
    written = [f for f, text in files.items() if write_text(out / f, text)]
    removed = []
    for f in out.glob('art_*.c'):   # a group that was renamed or deleted leaves its old file behind
        top = f.read_text(encoding='utf-8', errors='replace')[:400]
        if f.name not in files and any(m in top for m in (GENERATED,) + OLD_GENERATED):
            f.unlink()
            removed.append(f.name)
    return [], written, removed


