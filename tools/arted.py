def open_project(folder):
    """The art project in folder: (Project, False), or (Project, True) when there was none and a blank one
    was made, the folder too if it did not exist."""
    folder = Path(folder)
    if (folder / 'art.json').exists():
        return Project(folder), False
    if folder.exists() and not folder.is_dir():
        raise NotADirectoryError('%s is a file, not a folder' % folder)
    return Project.create(folder), True


class FolderDialog:
    """Asks for the art project's folder, typed or picked with Browse. wait() returns it (a Path) or None."""

    def __init__(self, root, initial, title='Art folder'):
        self.result = None
        w = self.w = tk.Toplevel(root)
        w.title(title)
        w.resizable(True, False)
        f = ttk.Frame(w, padding=12)
        f.pack(fill='both', expand=True)
        ttk.Label(f, text='The folder the art lives in: its JSON files are kept there. A folder that does not exist '
                  'yet is made, with a blank art project in it.', wraplength=560, justify='left'
                  ).grid(row=0, column=0, columnspan=2, sticky='w', pady=(0, 8))
        self.var = tk.StringVar(value=initial or '')
        self.entry = ttk.Entry(f, textvariable=self.var, width=70)
        self.entry.grid(row=1, column=0, sticky='we')
        ttk.Button(f, text='Browse...', command=self.browse).grid(row=1, column=1, padx=(6, 0))
        f.columnconfigure(0, weight=1)
        self.note = ttk.Label(f)
        self.note.grid(row=2, column=0, columnspan=2, sticky='w', pady=(6, 0))
        b = ttk.Frame(f)
        b.grid(row=3, column=0, columnspan=2, sticky='e', pady=(10, 0))
        ttk.Button(b, text='Open', command=self.ok, default='active').pack(side='left', padx=2)
        ttk.Button(b, text='Cancel', command=self.cancel).pack(side='left')
        self.entry.bind('<Return>', lambda e: self.ok())
        w.bind('<Escape>', lambda e: self.cancel())
        w.protocol('WM_DELETE_WINDOW', self.cancel)
        self.var.trace_add('write', lambda *a: self.describe())
        self.describe()
        self.entry.focus_set()
        self.entry.icursor('end')
        w.lift()     # in front, even of the terminal it was started from
        w.attributes('-topmost', True)
        w.after(300, lambda: w.winfo_exists() and w.attributes('-topmost', False))
        self.entry.focus_force()

    def folder(self):
        t = self.var.get().strip().strip('"')
        if not t:
            return None
        p = Path(os.path.expanduser(t))
        return p if p.is_absolute() else Path.cwd() / p

    def describe(self):
        """Says what Open will do with the folder typed."""
        p = self.folder()
        if p is None:
            text = 'Type a folder, or Browse to one.'
        elif (p / 'art.json').exists():
            text = 'Opens the art project there.'
        elif p.exists() and not p.is_dir():
            text = 'That is a file, not a folder.'
        elif p.exists():
            text = 'There is no art project there yet: Open makes a blank one in it.'
        else:
            text = 'That folder does not exist yet: Open makes it, with a blank art project in it.'
        self.note.config(text=text)
        return text

    def browse(self):
        p = self.folder()
        start = p if p and p.is_dir() else p.parent if p and p.parent.is_dir() else Path.cwd()
        d = filedialog.askdirectory(parent=self.w, initialdir=str(start), title='Art folder', mustexist=False)
        if d:
            self.var.set(str(Path(d)))

    def ok(self):
        p = self.folder()
        if p is None or (p.exists() and not p.is_dir()):
            self.w.bell()
            return
        self.result = p
        self.w.destroy()

    def cancel(self):
        self.w.destroy()

    def wait(self):
        self.w.wait_window()
        return self.result


