    # ---- model
    def frame(self):
        return self.s['frames'][self.fi]

    def base(self):
        return pal_cols(self.app.proj, self.g.get('preview', ''))

    def tile_colors(self):
        return spr_cols(self.base(), get_int(self.subpal, 0, 3, 0))

    def set_label(self, v):
        self.app.hist.checkpoint(self.g)
        if v.strip():
            self.s['label'] = v.strip()
        else:
            self.s.pop('label', None)
        return None

    # ---- lists
    def fill_frames(self):
        lb = self.frames
        lb.delete(0, 'end')
        for k, fr in enumerate(self.s['frames']):
            lb.insert('end', '%d   %d part%s' % (k, len(fr), '' if len(fr) == 1 else 's'))
        lb.selection_set(self.fi)
        lb.see(self.fi)

    @staticmethod
    def part_text(k, p):
        a = p[3]
        return '%2d  %+4d,%+4d  tile %3d  pal %d%s%s%s' % (k, p[0], p[1], p[2], a & 7, '  X' if a & FLIP_X else '',
                                                           '  Y' if a & FLIP_Y else '', '  behind' if a & PRIORITY else '')

    def fill_parts(self):
        lb = self.parts
        lb.delete(0, 'end')
        for k, p in enumerate(self.frame()):
            lb.insert('end', self.part_text(k, p))
        if 0 <= self.part < len(self.frame()):
            lb.selection_set(self.part)
            lb.see(self.part)

    def update_part_row(self):
        if 0 <= self.part < len(self.frame()):
            self.parts.delete(self.part)
            self.parts.insert(self.part, self.part_text(self.part, self.frame()[self.part]))
            self.parts.selection_set(self.part)

    def select_part(self, k, from_list=False):
        fr = self.frame()
        self.part = self.st['part'] = k if 0 <= k < len(fr) else -1
        if not from_list:
            self.fill_parts()
        if self.part >= 0:
            a = fr[self.part][3]
            self.pfx.set(bool(a & FLIP_X))
            self.pfy.set(bool(a & FLIP_Y))
            self.pbh.set(bool(a & PRIORITY))
            self.ppal.set(str(a & 7))
            if (a & 3) != get_int(self.subpal, 0, 3, 0):
                self.subpal.set(str(a & 3))
                self.subpal_changed()
            self.panel.select(fr[self.part][2])
        self.redraw()

    def part_chosen(self, e=None):
        sel = self.parts.curselection()
        if sel:
            self.select_part(sel[0], from_list=True)

    def frame_chosen(self, e=None):
        sel = self.frames.curselection()
        if sel and sel[0] != self.fi:
            self.show_frame(sel[0])

    def show_frame(self, k, part=-1):
        self.fi = self.st['frame'] = max(0, min(k, len(self.s['frames']) - 1))
        self.fill_frames()
        self.select_part(part)

    # ---- the canvas
    def zoom(self):
        return get_int(self.zoom_var, 1, 24, 8)

    def zoom_changed(self):
        self.st['zoom'] = self.zoom()
        self.redraw()

    def redraw(self):
        if self.drag is None or self.view is None:
            x0, y0, x1, y1 = sprite_bounds(self.s)
            self.view = (x0 - 8, y0 - 8, x1 + 8, y1 + 8)
        x0, y0, x1, y1 = self.view
        w, h, z = x1 - x0, y1 - y0, self.zoom()
        self.zi = ZImage(w, h, z, render_sprite(self.frame(), self.g['sprite_tiles'], self.base(), x0, y0, w, h))
        cv = self.cv
        cv.delete('all')
        cv.create_image(0, 0, anchor='nw', image=self.zi.img)
        cv.configure(width=w * z, height=h * z)

        def X(v):
            return (v - x0) * z

        def Y(v):
            return (v - y0) * z
        bw, bh, bx, by = self.s['box']
        cv.create_rectangle(X(bx), Y(by), X(bx + bw), Y(by + bh), outline=BOX, dash=(4, 3))
        cv.create_line(X(0) - 3 * z, Y(0), X(0) + 3 * z, Y(0), fill=ORIGIN, width=2)
        cv.create_line(X(0), Y(0) - 3 * z, X(0), Y(0) + 3 * z, fill=ORIGIN, width=2)
        t = self.panel.sel
        for k, p in enumerate(self.frame()):
            if k != self.part and (self.outlines.get() or p[2] == t):
                cv.create_rectangle(X(p[0]), Y(p[1]), X(p[0] + 8) - 1, Y(p[1] + 8) - 1, outline=USE if p[2] == t else GRID)
        if 0 <= self.part < len(self.frame()):
            p = self.frame()[self.part]
            cv.create_rectangle(X(p[0]), Y(p[1]), X(p[0] + 8), Y(p[1] + 8), outline=SEL, width=2)

    def to_sprite(self, e):
        z = self.zoom()
        return self.view[0] + e.x // z, self.view[1] + e.y // z

    def part_at(self, x, y):
        ts, inside = self.g['sprite_tiles'], None
        for k, p in enumerate(self.frame()):
            if p[0] <= x < p[0] + 8 and p[1] <= y < p[1] + 8:
                if 0 <= p[2] < len(ts) and tpx(ts[p[2]], p[3], x - p[0], y - p[1]):
                    return k
                if inside is None:
                    inside = k
        return inside

    def press(self, e):
        self.cv.focus_set()
        k = self.part_at(*self.to_sprite(e))
        self.select_part(-1 if k is None else k)
        if k is not None:
            p = self.frame()[k]
            self.drag = [e.x, e.y, p[0], p[1], False]

    def motion(self, e):
        if not self.drag or self.part < 0:
            return
        sx, sy, ox, oy, moved = self.drag
        z = self.zoom()
        nx = max(-128, min(127, ox + round((e.x - sx) / z)))
        ny = max(-128, min(127, oy + round((e.y - sy) / z)))
        p = self.frame()[self.part]
        if (nx, ny) != (p[0], p[1]):
            if not moved:
                self.app.hist.checkpoint(self.g)
                self.drag[4] = True
            p[0], p[1] = nx, ny
            self.redraw()
            self.update_part_row()

    def release(self, e):
        if self.drag:
            moved, self.drag = self.drag[4], None
            if moved:
                self.redraw()
                self.anim_draw()

    def hover(self, e):
        x, y = self.to_sprite(e)
        k = self.part_at(x, y)
        self.app.status('x %d, y %d from the origin%s' % (x, y, '' if k is None else '   part %d' % k))

    def on_key(self, e):
        if self.part < 0:
            return False
        step = 8 if e.state & 0x1 else 1
        moves = {'Left': (-step, 0), 'Right': (step, 0), 'Up': (0, -step), 'Down': (0, step)}
        if e.keysym in moves:
            dx, dy = moves[e.keysym]
            p = self.frame()[self.part]
            self.app.hist.checkpoint(self.g, merge=('nudge', self.loc, self.fi, self.part))
            p[0], p[1] = max(-128, min(127, p[0] + dx)), max(-128, min(127, p[1] + dy))
            self.update_part_row()
            self.redraw()
            self.anim_draw()
        elif e.keysym in ('Delete', 'BackSpace'):
            self.part_del()
        elif e.keysym.lower() in ('x', 'y'):
            var = self.pfx if e.keysym.lower() == 'x' else self.pfy
            var.set(not var.get())
            self.attr_changed()
        else:
            return False
        return True

    # ---- parts
    def attr_changed(self):
        if self.part < 0:
            return
        p = self.frame()[self.part]
        a = get_int(self.ppal, 0, 7, 0) | (FLIP_X if self.pfx.get() else 0) | (FLIP_Y if self.pfy.get() else 0) | \
            (PRIORITY if self.pbh.get() else 0)
        if a != p[3]:
            self.app.hist.checkpoint(self.g, merge=('attr', self.loc, self.fi, self.part))
            p[3] = a
            self.update_part_row()
            if (a & 3) != get_int(self.subpal, 0, 3, 0):
                self.subpal.set(str(a & 3))
                self.subpal_changed()
            self.redraw()
            self.anim_draw()

    def part_add(self):
        t = self.panel.sel
        if t < 0:
            return
        fr = self.frame()
        if 0 <= self.part < len(fr):
            x, y = fr[self.part][0] + 8, fr[self.part][1]
        else:
            x, y = self.s['box'][2], self.s['box'][3]
        self.app.hist.checkpoint(self.g)
        fr.insert(0, [x, y, t, get_int(self.subpal, 0, 3, 0)])
        self.parts_changed(0)

    def part_use(self):
        if 0 <= self.part < len(self.frame()) and self.panel.sel >= 0:
            self.app.hist.checkpoint(self.g)
            self.frame()[self.part][2] = self.panel.sel
            self.parts_changed(self.part)

    def part_copy(self):
        fr = self.frame()
        if 0 <= self.part < len(fr):
            p = list(fr[self.part])
            p[0] = min(127, p[0] + 8)
            self.app.hist.checkpoint(self.g)
            fr.insert(self.part, p)
            self.parts_changed(self.part)

    def part_del(self):
        fr = self.frame()
        if 0 <= self.part < len(fr):
            self.app.hist.checkpoint(self.g)
            del fr[self.part]
            self.parts_changed(min(self.part, len(fr) - 1))

    def part_move(self, d):
        fr, j = self.frame(), self.part + d
        if 0 <= self.part < len(fr) and 0 <= j < len(fr):
            self.app.hist.checkpoint(self.g)
            fr[self.part], fr[j] = fr[j], fr[self.part]
            self.parts_changed(j)

    def parts_changed(self, select):
        self.fill_frames()
        self.select_part(select)
        self.anim_draw()

    # ---- frames
    def frame_new(self):
        self.app.hist.checkpoint(self.g)
        self.s['frames'].insert(self.fi + 1, [])
        self.show_frame(self.fi + 1)

    def frame_copy(self):
        self.app.hist.checkpoint(self.g)
        self.s['frames'].insert(self.fi + 1, copy.deepcopy(self.frame()))
        self.show_frame(self.fi + 1)

    def frame_del(self):
        if len(self.s['frames']) > 1:
            self.app.hist.checkpoint(self.g)
            del self.s['frames'][self.fi]
            self.show_frame(self.fi)

    def frame_move(self, d):
        frs, j = self.s['frames'], self.fi + d
        if 0 <= j < len(frs):
            self.app.hist.checkpoint(self.g)
            frs[self.fi], frs[j] = frs[j], frs[self.fi]
            self.show_frame(j)

    # ---- box
    def box_changed(self):
        b = [get_int(self.boxv[0], 0, 255, 0), get_int(self.boxv[1], 0, 255, 0),
             get_int(self.boxv[2], -128, 127, 0), get_int(self.boxv[3], -128, 127, 0)]
        if b != self.s['box']:
            self.app.hist.checkpoint(self.g, merge=('box', self.loc))
            self.s['box'] = b
            self.redraw()

    def box_fit(self):
        fr = self.s['frames'][0]
        if fr:
            x0, y0 = min(p[0] for p in fr), min(p[1] for p in fr)
            x1, y1 = max(p[0] for p in fr) + 8, max(p[1] for p in fr) + 8
            for v, n in zip(self.boxv, (x1 - x0, y1 - y0, x0, y0)):
                v.set(str(n))
            self.box_changed()

    # ---- tile panel host
    def subpal_changed(self):
        self.st['subpal'] = get_int(self.subpal, 0, 3, 0)
        self.panel.recolor()

    def tile_selected(self, i):
        self.st['tile'] = i
        if self.view is not None:
            self.redraw()

    def pixels_changed(self, t):
        self.redraw()
        self.anim_draw()

    def tiles_changed(self):
        self.fill_parts()
        self.redraw()
        self.anim_draw()

    def recolor(self):
        self.panel.recolor()
        self.redraw()
        self.anim_draw()

    # ---- animation
    def anim_draw(self):
        frames = self.s['frames']
        x0, y0, x1, y1 = sprite_bounds(self.s)
        w, h, z = x1 - x0, y1 - y0, self.app.z(3)
        px = render_sprite(frames[self.anim_k % len(frames)], self.g['sprite_tiles'], self.base(), x0, y0, w, h)
        self.azi = ZImage(w, h, z, px)
        self.anim.delete('all')
        self.anim.create_image(0, 0, anchor='nw', image=self.azi.img)
        self.anim.configure(width=w * z, height=h * z)

    def anim_tick(self):
        self.anim_k = (self.anim_k + 1) % len(self.s['frames'])
        self.anim_draw()
        self.later(int(1000 / get_int(self.fps, 1, 60, 6)), self.anim_tick)


