def make_editor(master, app, loc):
    proj, parts = app.proj, loc.split('/')
    if loc == 'pal':
        return PaletteEditor(master, app, loc)
    if loc == 'fonts':
        return font_gallery(master, app, loc)
    if parts[0] == 'font':
        return FontEditor(master, app, loc, int(parts[1]))
    if loc == 'pics':
        return picture_gallery(master, app, loc)
    if parts[0] == 'pic':
        return PictureEditor(master, app, loc, int(parts[1]))
    g = proj.group(parts[1])
    if len(parts) == 2:
        return GroupEditor(master, app, loc, g)
    kind = parts[2]
    if kind == 'spr':
        return TileSetEditor(master, app, loc, g, 'sprite_tiles', '%s sprite tiles' % g['name'],
                             'Value 0 is transparent; 1..3 are the 3 colors of the sprite palette a part uses.', g)
    if kind == 'bg':
        return TileSetEditor(master, app, loc, g, 'bg_tiles', '%s background tiles' % g['name'],
                             'The tiles of this group\'s metatiles. Values 0..3 are the 4 palette colors.', g)
    if kind == 'sprites':
        return sprite_gallery(master, app, loc, g)
    if kind == 'sprite':
        return SpriteEditor(master, app, loc, g, int(parts[3]))
    if kind == 'mts':
        return metatile_gallery(master, app, loc, g)
    return MetatileEditor(master, app, loc, g, int(parts[3]))


