def hx(v, n=2):
    return '0x' + ('%X' % v).rjust(n, '0')


def head(what, src):
    return '/* %s\n * %s from %s/. Do not edit: change %s/ and export again. */\n' % (what, GENERATED, src, src)


def slotted(tile, attr):
    return (tile, attr) if tile < 256 else (tile - 256, attr | SLOT1)


def tiles_c(name, tiles, label=None, static=False):
    s = '%sconst uint8_t %s[%d] = {\n' % ('static ' if static else '', name, len(tiles) * 16)
    for i, t in enumerate(tiles):
        s += '    ' + ','.join(hx(b) for b in encode(t)) + ', /* %d%s */\n' % (i, ' ' + label(i) if label else '')
    return s + '};\n'


def entry_c(c):
    t, a = slotted(c[0], c[1])
    return '{%d,%s}' % (t, hx(a))


ART_H_TOP = '''/* art.h - the game art as Roswell Color data.
 * %s from %s/. Do not edit: change %s/ and export again.
 *
 * PALETTES
 *   ART_PAL_<NAME>[4]       background palette, 4 colors (as imported: shade 0 light .. 3 dark).
 *   ART_PAL_<NAME>_SPR[4*3] 4 sprite palettes. Sprite palette k holds the 4 colors minus color k,
 *                           in order. Load all 4 into sprite palettes 0..3 (or 4..7).
 *   The old fx.fade / fx.invert / fx.cycle effects remapped shades; do them by loading altered palettes.
 *
 * TILES
 *   Each set is const uint8_t data, 16 bytes per tile, ready for rc_bank_load(). Load a set into
 *   one bank. A set over 256 tiles: bind slot 0 to tiles 0..255 and slot 1 to tiles 256.., and the
 *   map entries and sprite parts that need slot 1 already carry RC_MAP_SLOT1 / RC_SPRITE_SLOT1.
 *   Mirror-image tiles are stored once and drawn with RC_FLIP_X / RC_FLIP_Y.
 *
 * SPRITES (art_sprite): a metasprite per animation. Each frame is a list of 8x8 hardware sprites
 *   (parts). dx/dy is a part's offset from the sprite's draw origin, which is the top-left corner the
 *   old blit() used. attr holds the palette 0..3 (one of the 4 sprite palettes above) and the flip
 *   and slot bits; to use palettes 4..7 add 4. Earlier parts are on top. A cell that used all 4
 *   shades is two parts at the same place, so it costs two of the 10 sprites a line can show.
 *   Directional sprites are split into _DOWN, _UP, _SIDE. SIDE faces right; the old engine drew
 *   left-facing by mirroring, which is RC_FLIP_X on every part and dx -> w - 8 - dx.
 *
 * METATILES (art_metatile): 16x16 background tiles. cells holds 4 map entries per frame
 *   (top-left, top-right, bottom-left, bottom-right); speed is frames per animation frame at 60 Hz.
 *
 * PICTURES (art_picture): the place pictures, 20x10 tiles (160x80). They cover screen rows 8..87 of the
 *   original layout: the photo window was rows 12..87 under a 12-pixel name bar. Load the tiles into
 *   a bank, bind it, rc_map_load() the map. One palette (the old game showed them with ART_PAL_FAX).
 *
 * FONTS: ART_FONT_<NAME>_*. A glyph is _W x _H tiles, stored together row by row: glyph g is tiles
 *   g*W*H .. g*W*H + W*H - 1 of _TILES. _GLYPH[(unsigned char)c] is the glyph of character c, which is
 *   Latin-1 (write e-acute as "\\xe9"); a character the font lacks gives its fallback glyph.
 *   ART_FONT_TILES, ART_FONT_GLYPH, ART_FONT_W and the rest without a name are the first font.
 *   The imported font (main) is 1x1 tiles for ASCII 0x20..0x7F in order (so its glyph is also c - 0x20),
 *   shade 3 on shade 0; its lowercase letters repeat the capitals, except 'v', the old down-arrow glyph.
 */
#ifndef ART_H
#define ART_H

#include <stdint.h>
#include "rc_dev.h"

typedef struct art_part { int8_t dx, dy; uint8_t tile, attr; } art_part;
typedef struct art_frame { const art_part *parts; uint8_t count; } art_frame;
typedef struct art_sprite {
    const art_frame *frames;
    uint8_t frame_count;
    uint8_t w, h;      /* bounding box size in pixels */
    int8_t x, y;       /* bounding box top-left, from the draw origin */
} art_sprite;
typedef struct art_metatile { const rc_map_entry *cells; uint8_t frame_count; uint8_t speed; } art_metatile;
typedef struct art_picture {
    const char *id;    /* the place id, e.g. "rome" */
    const uint8_t *tiles;
    uint16_t tile_count;
    rc_map_data map;
} art_picture;
'''


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def c_comment(s):
    return str(s).replace('*/', '* /').replace('/*', '/ *')


