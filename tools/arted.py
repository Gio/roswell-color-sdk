        items.append((s['name'], x1 - x0, y1 - y0, render_sprite(fr, g['sprite_tiles'], base, x0, y0, x1 - x0, y1 - y0),
                      app.z(3), 'g/%s/sprite/%d' % (g['name'], i)))
