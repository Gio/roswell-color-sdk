class Gallery(Editor):
    """Thumbnails; a click opens one."""

    def __init__(self, master, app, loc, title, items, new=None, note=''):
        super().__init__(master, app, loc)
        top = ttk.Frame(self)
        top.pack(fill='x')
        self.heading(top, title).pack(side='left')
        if new:
            ttk.Button(top, text='New', command=new).pack(side='right')
        if note:
            ttk.Label(self, text=note, foreground=DIM).pack(anchor='w', pady=(2, 0))
        f, self.cv = scrolled(self, bg=app.bg)
        f.pack(fill='both', expand=True, pady=app.z(6))
        self.items = [(lab, ZImage(w, h, z, px).img, l) for lab, w, h, px, z, l in items]
        self.cv.bind('<Configure>', self.layout)

    def layout(self, e=None):
        cv, z = self.cv, self.app.z
        cv.delete('all')
        W, pad = max(cv.winfo_width(), z(200)), z(12)
        x = y = pad
        rowh = 0
        for k, (lab, img, loc) in enumerate(self.items):
            w, h = max(img.width(), z(90)), img.height() + z(22)
            if x + w > W - pad and x > pad:
                x, y, rowh = pad, y + rowh + pad, 0
            tag = 'i%d' % k
            cv.create_image(x, y, anchor='nw', image=img, tags=tag)
            cv.create_text(x, y + img.height() + z(3), anchor='nw', text=lab, width=w, tags=tag)
            cv.tag_bind(tag, '<Button-1>', lambda e, l=loc: self.app.goto(l))
            cv.tag_bind(tag, '<Enter>', lambda e: cv.configure(cursor='hand2'))
            cv.tag_bind(tag, '<Leave>', lambda e: cv.configure(cursor=''))
            x, rowh = x + w + pad, max(rowh, h)
        cv.configure(scrollregion=(0, 0, W, y + rowh + pad))


