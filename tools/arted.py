def reserved_group(name):
    """Why a group cannot have this name (its C or file names would clash), or None."""
    c = cid(name)
    if c in RESERVED_FILES or any(c == r or c.startswith(r + '_') for r in RESERVED_GROUPS):
        return 'A group cannot be called %s: its C names would clash with the palettes, fonts or pictures.' % name
    return None


# ================================================================ tiles
def tile_from_rows(rows):
    return bytearray(int(c) for r in rows for c in r)


def tile_rows(t):
    return [''.join(str(v) for v in t[y * 8:y * 8 + 8]) for y in range(8)]


def blank_tile():
    return bytearray(64)


def tpx(t, attr, x, y):
    """Pixel (x, y) of tile t drawn with attr's flips."""
    return t[((7 - y if attr & FLIP_Y else y) << 3) | (7 - x if attr & FLIP_X else x)]


def flip_x(t):
    return bytearray(t[(i & ~7) | (7 - (i & 7))] for i in range(64))


def flip_y(t):
    return bytearray(t[((7 - (i >> 3)) << 3) | (i & 7)] for i in range(64))


def rotate(t):
    """A quarter turn clockwise."""
    return bytearray(t[(7 - (i & 7)) * 8 + (i >> 3)] for i in range(64))


def flood(t, x, y, v, w=8, h=8):
    """Fills the 4-connected area of the color at (x, y) of w x h pixels t with v. Returns whether anything
    changed."""
    old = t[y * w + x]
    if old == v:
        return False
    todo = [(x, y)]
    while todo:
        x, y = todo.pop()
        if 0 <= x < w and 0 <= y < h and t[y * w + x] == old:
            t[y * w + x] = v
            todo += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    return True


def grid_flip_x(p, w, h):
    return bytearray(p[y * w + w - 1 - x] for y in range(h) for x in range(w))


def grid_flip_y(p, w, h):
    return bytearray(p[(h - 1 - y) * w + x] for y in range(h) for x in range(w))


def grid_rotate(p, n):
    """A quarter turn clockwise of n x n pixels."""
    return bytearray(p[(n - 1 - x) * n + y] for y in range(n) for x in range(n))


def grid_paste(p, w, h, src, sw, sh):
    """p with src (sw x sh) laid over its top-left corner."""
    out = bytearray(p)
    for y in range(min(h, sh)):
        out[y * w:y * w + min(w, sw)] = src[y * sw:y * sw + min(w, sw)]
    return out


def encode(t):
    """Roswell Color tile bytes: per row, low bit plane then high bit plane, bit 7 = leftmost pixel."""
    b = []
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            v = t[y * 8 + x]
            lo |= (v & 1) << (7 - x)
            hi |= ((v >> 1) & 1) << (7 - x)
        b += [lo, hi]
    return b


# ================================================================ fonts
def default_fallback(chars):
    return '?' if '?' in chars else ' ' if ' ' in chars else chars[:1]


def glyph_of(f, ch):
    """The glyph a font draws ch with: its own, else the fallback's, else glyph 0."""
    g = f['chars'].find(ch)
    if g < 0:
        g = f['chars'].find(f.get('fallback') or '\0')
    return max(g, 0)


def glyph_tile(f, g, x, y):
    """(tile number, pixel index in it) of pixel (x, y) of glyph g."""
    w = f['size'][0]
    return g * w * f['size'][1] + (y >> 3) * w + (x >> 3), (y & 7) * 8 + (x & 7)


def glyph_get(f, g):
    """Glyph g's pixels, w*8 x h*8, row by row."""
    w, h = f['size']
    out = bytearray()
    for y in range(h * 8):
        for x in range(w * 8):
            t, i = glyph_tile(f, g, x, y)
            out.append(f['tiles'][t][i])
    return out


def glyph_put(f, g, px):
    w, h = f['size']
    for y in range(h * 8):
        for x in range(w * 8):
            t, i = glyph_tile(f, g, x, y)
            f['tiles'][t][i] = px[y * w * 8 + x]


def font_resize(f, w, h):
    """Makes every glyph w x h tiles, keeping its top-left pixels (cut or padded with 0)."""
    ow, oh = f['size']
    old = [glyph_get(f, g) for g in range(len(f['chars']))]
    f['size'] = [w, h]
    f['tiles'][:] = [blank_tile() for _ in range(len(f['chars']) * w * h)]
    for g, px in enumerate(old):
        new = bytearray(w * 8 * h * 8)
        for y in range(min(oh, h) * 8):
            for x in range(min(ow, w) * 8):
                new[y * w * 8 + x] = px[y * ow * 8 + x]
        glyph_put(f, g, new)


def font_set_chars(f, chars):
    """Gives the font these characters; each glyph stays with its character, new ones are blank.
    Returns how many glyphs with pixels were dropped."""
    n = f['size'][0] * f['size'][1]
    old = {ch: f['tiles'][g * n:(g + 1) * n] for g, ch in enumerate(f['chars'])}
    lost = sum(1 for ch, ts in old.items() if ch not in chars and any(any(t) for t in ts))
    f['tiles'][:] = [t for ch in chars for t in (old.get(ch) or [blank_tile() for _ in range(n)])]
    f['chars'] = chars
    if f.get('fallback') not in chars or not f.get('fallback'):
        f['fallback'] = default_fallback(chars)
    return lost


def chars_problem(chars):
    """Why a font cannot have these characters, or None."""
    if not isinstance(chars, str) or not chars:
        return 'A font needs at least one character.'
    bad = sorted({c for c in chars if not 1 <= ord(c) <= 255})
    if bad:
        return ('Only Latin-1 characters (U+0001..U+00FF) fit one byte in C, so %s cannot be in a font.'
                % ' '.join('U+%04X' % ord(c) for c in bad[:8]))
    dup = sorted({c for c in chars if chars.count(c) > 1})
    if dup:
        return 'Each character can be in a font once; these are there twice: %s' % chars_text(''.join(dup))
    return None


def chars_text(chars):
    """chars as typed in the editor: \\ for a backslash, \\xNN for anything that does not show."""
    return ''.join('\\\\' if c == '\\' else c if c.isprintable() else '\\x%02x' % ord(c) for c in chars)


def parse_chars(text):
    """chars_text back to characters: (chars, None), or (None, why not)."""
    out = []
    for m in re.finditer(r'\\x([0-9a-fA-F]{2})|\\\\|\\(.?)|(.)', text, re.S):
        if m.group(1):
            out.append(chr(int(m.group(1), 16)))
        elif m.group(3) is not None:
            out.append(m.group(3))
        elif m.group(2) is not None:
            return None, 'Write a backslash as \\\\, and a character that does not show as \\x and 2 hex digits.'
        else:
            out.append('\\')
    chars = ''.join(out)
    return (None, chars_problem(chars)) if chars_problem(chars) else (chars, None)


def char_name(ch):
    """A character for a C comment, in ASCII."""
    o = ord(ch)
    return ('space' if ch == ' ' else 'backslash' if ch == '\\' else 'DEL' if o == 0x7f else
            "'%s'" % ch if 0x20 < o < 0x7f else '0x%02X' % o)


def blank_font(name, preview):
    """1x1 tiles for printable ASCII, all blank."""
    return {'name': name, 'preview': preview, 'size': [1, 1], 'chars': NEW_FONT_CHARS,
            'fallback': default_fallback(NEW_FONT_CHARS), 'tiles': [blank_tile() for _ in NEW_FONT_CHARS]}


def font_label(f, i):
    """What tile i of font f is, for the export's comments."""
    n = f['size'][0] * f['size'][1]
    return char_name(f['chars'][i // n]) + (' %d/%d' % (i % n + 1, n) if n > 1 else '')


# ================================================================ colors
def parse_hex(h):
    return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def to_hex(c):
    return '#' + ''.join('%02x' % v for v in c)


def rgb15(c):
    """An 8-bit RGB color as rc_color: red in bits 0..4, green 5..9, blue 10..14."""
    r, g, b = (int(v * 31 / 255 + 0.5) for v in c)
    return r | (g << 5) | (b << 10)


@functools.lru_cache(maxsize=None)
def shown(h):
    """The color the console shows for "#rrggbb", as "#rrggbb" (each channel cut to 5 bits)."""
    q = rgb15(parse_hex(h))
    return to_hex([(v << 3) | (v >> 2) for v in (q & 31, (q >> 5) & 31, (q >> 10) & 31)])


def cid(s):
    """C identifier part from a name: offPink -> OFF_PINK."""
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', s)
    return re.sub(r'^_|_$', '', re.sub(r'[^A-Za-z0-9]+', '_', s)).upper()


# ================================================================ JSON layout
def has_obj(v):
    return isinstance(v, dict) or (isinstance(v, list) and any(has_obj(x) for x in v))


def fmt(v, ind=0):
    """The layout tools/artx.js writes too: a container goes on one line when it holds no objects and fits
    in 160 columns, so a save rewrites only what changed."""
    c = dumps(v)
    if not isinstance(v, (list, dict)) or not v or (not has_obj(v) and ind + len(c) <= 160):
        return c
    pad, end = ' ' * (ind + 2), '\n' + ' ' * ind
    if isinstance(v, list):
        return '[\n' + ',\n'.join(pad + fmt(x, ind + 2) for x in v) + end + ']'
    return '{\n' + ',\n'.join(pad + dumps(k) + ': ' + fmt(x, ind + 2) for k, x in v.items()) + end + '}'


def dumps(v):
    """Compact JSON, UTF-8, with the characters that do not show (DEL, the C1 controls, no-break and soft
    hyphen) written as \\uNNNN, like the C0 controls already are."""
    return re.sub('[\x7f-\xa0\xad]', lambda m: '\\u%04x' % ord(m.group()),
                  json.dumps(v, separators=(',', ':'), ensure_ascii=False))


def write_text(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding='utf-8') == text:
        return False
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(text, encoding='utf-8', newline='\n')
    os.replace(tmp, path)
    return True


# ================================================================ paths
def default_export(root):
    """Where a project in root exports to when its art.json does not say: src/art beside root."""
    return Path(root).parent / 'src' / 'art'


def rel_path(path, start):
    """path relative to start, with / between parts (absolute when they are on different drives)."""
    try:
        return Path(os.path.relpath(Path(path).resolve(), Path(start).resolve())).as_posix()
    except ValueError:
        return Path(path).resolve().as_posix()


def source_name(root, out):
    """How the generated C names the project it came from: its path from the folder it shares with out."""
    root, out = Path(root).resolve(), Path(out).resolve()
    try:
        common = Path(os.path.commonpath([root, out]))
    except ValueError:
        return root.name
    return root.name if root == common else rel_path(root, common)


# ================================================================ the project
class Project:
    """All of assets/ in memory. Tiles are bytearrays of 64 pixels; map cells, metatile cells and sprite
    parts are lists, so the editor can change them in place."""

    def __init__(self, root):
        self.root = Path(root)
        self.files = set()
        self.load()

    @classmethod
    def create(cls, root, out=None):
        """Writes a blank art project to root (made if missing), which must not have one yet: a grey palette
        and a blank font, no groups or pictures. out is where it exports to (default: default_export).
        Returns it."""
        root = Path(root)
        if (root / 'art.json').exists():
            raise FileExistsError('%s already has an art project (art.json)' % root)
        p = cls.__new__(cls)
        p.root, p.files = root, set()
        p.settings = {'export': rel_path(out or default_export(root), root)}
        p.palettes = [{'name': 'grey', 'colors': list(GREYS)}]
        p.fonts = [blank_font('main', 'grey')]
        p.groups, p.pictures = [], []
        p.save()
        return p

    def _read(self, rel):
        self.files.add(rel)
        with open(self.root / rel, encoding='utf-8') as f:
            return json.load(f)

    def load(self):
        self.files = set()
        idx = self._read('art.json')
        self.settings = {'export': idx.get('export') or rel_path(default_export(self.root), self.root)}
        self.palettes = self._read('palettes.json')['palettes']
        self.fonts = []
        for n in idx.get('fonts', []):
            d = self._read('fonts/%s.json' % n)
            d['tiles'] = [tile_from_rows(t) for t in d['tiles']]
            d.setdefault('size', [1, 1])
            d.setdefault('chars', OLD_FONT_CHARS)
            d.setdefault('fallback', default_fallback(d['chars']))
            self.fonts.append(d)
        self.groups = []
        for g in idx['groups']:
            d = self._read('groups/%s.json' % g)
            d['sprite_tiles'] = [tile_from_rows(t) for t in d.get('sprite_tiles', [])]
            d['bg_tiles'] = [tile_from_rows(t) for t in d.get('bg_tiles', [])]
            d.setdefault('sprites', [])
            d.setdefault('metatiles', [])
            self.groups.append(d)
        self.pictures = []
        for p in idx['pictures']:
            d = self._read('pictures/%s.json' % p)
            d['tiles'] = [tile_from_rows(t) for t in d['tiles']]
            self.pictures.append(d)

    # ---- saving
    def documents(self):
        """(relative path, JSON value) for every file of the project."""
        yield 'art.json', {'fonts': [f['name'] for f in self.fonts], 'groups': [g['name'] for g in self.groups],
                           'pictures': [p['id'] for p in self.pictures], 'export': self.settings['export']}
        yield 'palettes.json', {'palettes': self.palettes}
        for f in self.fonts:
            d = {k: f[k] for k in ('name', 'preview', 'size', 'chars', 'fallback') if k in f}
            d.update((k, v) for k, v in f.items() if k not in d and k != 'tiles')
            d['tiles'] = [tile_rows(t) for t in f['tiles']]
            yield 'fonts/%s.json' % f['name'], d
        for g in self.groups:
            d = dict(g)
            d['sprite_tiles'] = [tile_rows(t) for t in g['sprite_tiles']]
            d['bg_tiles'] = [tile_rows(t) for t in g['bg_tiles']]
            yield 'groups/%s.json' % g['name'], d
        for p in self.pictures:
            d = dict(p)
            d['tiles'] = [tile_rows(t) for t in p['tiles']]
            yield 'pictures/%s.json' % p['id'], d

    def save(self):
        """Writes every file whose text changed. A font, group or picture that was renamed or deleted has
        its old file removed (only files this project loaded or saved, nothing else in the folder)."""
        written, now = 0, set()
        for rel, v in self.documents():
            written += write_text(self.root / rel, fmt(v) + '\n')
            now.add(rel)
        lower = {rel.lower(): rel for rel in now}
        for old in sorted(self.files - now):
            f = self.root / old
            if not f.exists():
                continue
            new = lower.get(old.lower())
            if new and os.path.samefile(f, self.root / new):
                os.replace(f, self.root / new)  # renamed in case only, on a case-blind file system
            else:
                f.unlink()
            written += 1
        self.files = now
        return written

    def export_dir(self):
        """Where the C goes: the folder art.json names, relative to the project."""
        return Path(os.path.normpath(self.root / self.settings['export']))

    # ---- lookups
    def palette(self, name):
        for p in self.palettes:
            if p['name'] == name:
                return p
        return self.palettes[0] if self.palettes else {'name': '?', 'colors': list(GREYS)}

    def group(self, name):
        return next(g for g in self.groups if g['name'] == name)


# ================================================================ tile references
def tile_users(proj, owner, kind):
    """Every place a tile set's tiles are used, as (cell list, index of the tile number in it, label).
    owner/kind: (group, 'sprite_tiles' | 'bg_tiles'), (picture, 'tiles') or (font, 'tiles')."""
    out = []
    if kind == 'sprite_tiles':
        for s in owner['sprites']:
            for i, fr in enumerate(s['frames']):
                out += [(p, 2, '%s[%d]' % (s['name'], i)) for p in fr]
    elif kind == 'bg_tiles':
        for m in owner['metatiles']:
            for i, fr in enumerate(m['frames']):
                out += [(c, 0, '%s[%d]' % (m['name'], i)) for c in fr]
    elif 'map' in owner:
        for y, row in enumerate(owner['map']):
            out += [(c, 0, 'row %d' % y) for c in row]
    return out


def tile_uses(proj, owner, kind, t):
    return [lab for cell, k, lab in tile_users(proj, owner, kind) if cell[k] == t]


def delete_tiles(proj, owner, kind, doomed):
    """Removes the given tile numbers (none may be in use) and renumbers every reference after them."""
    doomed = set(doomed)
    keep = [i for i in range(len(owner[kind])) if i not in doomed]
    new = {old: n for n, old in enumerate(keep)}
    for cell, k, _ in tile_users(proj, owner, kind):
        cell[k] = new[cell[k]]
    owner[kind][:] = [owner[kind][i] for i in keep]


def unused_tiles(proj, owner, kind):
    used = {cell[k] for cell, k, _ in tile_users(proj, owner, kind)}
    return [i for i in range(len(owner[kind])) if i not in used]


def find_copies(tiles):
    """{tile: (earlier tile, flips)} for every tile that is a copy or a mirror image of an earlier one:
    tile == the earlier tile drawn with those flips."""
    seen, out = {}, {}
    for i, t in enumerate(tiles):
        fx = flip_x(t)
        for v, f in ((t, 0), (fx, FLIP_X), (flip_y(t), FLIP_Y), (flip_y(fx), FLIP_X | FLIP_Y)):
            j = seen.get(bytes(v))
            if j is not None:
                out[i] = (j, f)
                break
        else:
            seen[bytes(t)] = i
    return out


def merge_copies(proj, owner, kind, copies):
    """Points everything that uses a copy (from find_copies) at the original, with the flips that make
    it look the same, and removes the copies."""
    for cell, k, _ in tile_users(proj, owner, kind):
        if cell[k] in copies:
            j, f = copies[cell[k]]
            cell[k], cell[k + 1] = j, cell[k + 1] ^ f
    delete_tiles(proj, owner, kind, list(copies))


# ================================================================ checks
def check(proj):
    """Everything that would make the export wrong or not compile, as a list of messages."""
    bad = []
    err = bad.append

    def tiles_ok(where, tiles, limit):
        if len(tiles) > limit:
            err('%s: %d tiles, over the %d limit' % (where, len(tiles), limit))
        for i, t in enumerate(tiles):
            if len(t) != 64 or any(v > 3 for v in t):
                err('%s: tile %d is not 8x8 pixels of 0..3' % (where, i))

    def ref_ok(where, tile, attr, count):
        if not (isinstance(tile, int) and 0 <= tile < count):
            err('%s: tile %r is not in its tile set (0..%d)' % (where, tile, count - 1))
        if not (isinstance(attr, int) and 0 <= attr <= 255) or attr & (SLOT1 | 0x10):
            err('%s: attr %r: only the palette (0..7), 0x20 flip X, 0x40 flip Y and 0x80 are allowed' % (where, attr))

    def names_ok(where, names):
        seen = set()
        for n in names:
            if not isinstance(n, str) or not NAME_RE.match(n):
                err('%s: name %r must be letters, digits and _ and start with a letter' % (where, n))
            elif cid(n) in seen:
                err('%s: two names come out as %s in C' % (where, cid(n)))
            seen.add(cid(n))

    names_ok('palettes', [p['name'] for p in proj.palettes])
    for p in proj.palettes:
        if len(p['colors']) != 4 or not all(re.match(r'^#[0-9a-fA-F]{6}$', c) for c in p['colors']):
            err('palette %s: needs 4 colors written #rrggbb' % p['name'])
    if not proj.fonts:
        err('fonts: needs at least one font')
    names_ok('fonts', [f['name'] for f in proj.fonts])
    for f in proj.fonts:
        F, size, chars = 'font %s' % f['name'], f.get('size'), f.get('chars')
        if not (isinstance(size, list) and len(size) == 2 and
                all(isinstance(v, int) and 1 <= v <= FONT_MAX_SIZE for v in size)):
            err('%s: size must be [w, h] in tiles, each 1..%d' % (F, FONT_MAX_SIZE))
            continue
        if chars_problem(chars):
            err('%s: %s' % (F, chars_problem(chars)))
            continue
        if not (isinstance(f.get('fallback'), str) and len(f['fallback']) == 1 and f['fallback'] in chars):
            err('%s: the fallback must be one of its characters' % F)
        n = len(chars) * size[0] * size[1]
        if len(f['tiles']) != n:
            err('%s: %d characters of %dx%d tiles need %d tiles, it has %d' % (F, len(chars), size[0], size[1], n, len(f['tiles'])))
        tiles_ok(F, f['tiles'], FONT_MAX_TILES)
    names_ok('groups', [g['name'] for g in proj.groups])
    for g in proj.groups:
        G = g['name']
        if isinstance(G, str) and reserved_group(G):
            err('%s: %s' % (G, reserved_group(G)))
        tiles_ok(G + ' sprite tiles', g['sprite_tiles'], MAX_SPRITE_TILES)
        tiles_ok(G + ' bg tiles', g['bg_tiles'], MAX_BG_TILES)
        names_ok(G + ' sprites', [s['name'] for s in g['sprites']])
        names_ok(G + ' metatiles', [m['name'] for m in g['metatiles']])
        if g['sprites'] and not g['sprite_tiles']:
            err('%s: has sprites but no sprite tiles' % G)
        if g['metatiles'] and not g['bg_tiles']:
            err('%s: has metatiles but no bg tiles' % G)
        for s in g['sprites']:
            w = '%s sprite %s' % (G, s['name'])
            if not 1 <= len(s['frames']) <= 255:
                err('%s: needs 1..255 frames' % w)
            bw, bh, bx, by = s['box']
            if not (0 <= bw <= 255 and 0 <= bh <= 255 and -128 <= bx <= 127 and -128 <= by <= 127):
                err('%s: box %r out of range (w, h 0..255; x, y -128..127)' % (w, s['box']))
            for i, fr in enumerate(s['frames']):
                if len(fr) > MAX_PARTS:
                    err('%s[%d]: %d parts, over the %d hardware sprites' % (w, i, len(fr), MAX_PARTS))
                for p in fr:
                    if not (-128 <= p[0] <= 127 and -128 <= p[1] <= 127):
                        err('%s[%d]: part offset %d,%d out of -128..127' % (w, i, p[0], p[1]))
                    ref_ok('%s[%d]' % (w, i), p[2], p[3], len(g['sprite_tiles']))
        for m in g['metatiles']:
            w = '%s metatile %s' % (G, m['name'])
            if not 1 <= len(m['frames']) <= 255:
                err('%s: needs 1..255 frames' % w)
            if not 1 <= m['speed'] <= 255:
                err('%s: speed must be 1..255' % w)
            for i, fr in enumerate(m['frames']):
                if len(fr) != 4:
                    err('%s[%d]: needs 4 cells' % (w, i))
                for c in fr:
                    ref_ok('%s[%d]' % (w, i), c[0], c[1], len(g['bg_tiles']))
    names_ok('pictures', [p['id'] for p in proj.pictures])
    for p in proj.pictures:
        w = 'picture ' + p['id']
        tiles_ok(w, p['tiles'], MAX_PICTURE_TILES)
        if not p['tiles']:
            err(w + ': has no tiles')
        widths = {len(r) for r in p['map']}
        if len(widths) != 1 or not p['map'] or not 1 <= len(p['map'][0]) <= 32 or len(p['map']) > 32:
            err(w + ': map rows must all be the same width, up to 32x32')
        for y, row in enumerate(p['map']):
            for c in row:
                ref_ok('%s row %d' % (w, y), c[0], c[1], len(p['tiles']))
    return bad


