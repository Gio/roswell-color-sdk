class CellCanvas(tk.Canvas):
    """The cells of a map (a picture, or a metatile frame as 2x2), editable with the host's brush."""

    def __init__(self, master, app, ed):
        super().__init__(master, highlightthickness=0, bg=EMPTY, cursor='crosshair')
        self.app, self.ed, self.zi, self.last, self.pending = app, ed, None, None, False
        for b, n in ((0, 1), (1, 3)):
            self.bind('<ButtonPress-%d>' % n, lambda e, b=b: self.press(e, b))
            self.bind('<B%d-Motion>' % n, lambda e, b=b: self.drag(e, b))
        self.bind('<Motion>', self.hover)
        self.bind('<Leave>', lambda e: self.app.status(''))

    def size(self):
        rows = self.ed.rows()
        return (len(rows[0]) if rows else 0), len(rows)

    def redraw(self):
        z = self.ed.zoom()
        W, H, px = render_map(self.ed.rows(), self.ed.tiles(), self.ed.colors())
        self.zi = ZImage(W, H, z, px)
        self.delete('all')
        self.create_image(0, 0, anchor='nw', image=self.zi.img)
        self.configure(width=W * z, height=H * z)
        self.overlay()

    def update_tile(self, t):
        if not self.zi:
            return
        ts, cols = self.ed.tiles(), self.ed.colors()
        for cy, row in enumerate(self.ed.rows()):
            for cx, c in enumerate(row):
                if c[0] == t:
                    self.zi.put(cx * 8, cy * 8, 8, 8, cell_px(c, ts, cols))

    def overlay(self):
        self.delete('ov')
        z8, (w, h), rows = 8 * self.ed.zoom(), self.size(), self.ed.rows()
        if self.ed.grid_on.get():
            for x in range(1, w):
                self.create_line(x * z8, 0, x * z8, h * z8, fill=GRID, tags='ov')
            for y in range(1, h):
                self.create_line(0, y * z8, w * z8, y * z8, fill=GRID, tags='ov')
        if self.ed.uses_on.get():
            t = self.ed.panel.sel
            for cy, row in enumerate(rows):
                for cx, c in enumerate(row):
                    if c[0] == t:
                        self.create_rectangle(cx * z8 + 1, cy * z8 + 1, (cx + 1) * z8 - 1, (cy + 1) * z8 - 1, outline=USE, tags='ov')
        cur = self.ed.cur
        if cur and 0 <= cur[0] < w and 0 <= cur[1] < h:
            self.create_rectangle(cur[0] * z8, cur[1] * z8, (cur[0] + 1) * z8, (cur[1] + 1) * z8, outline=SEL, width=2, tags='ov')

    def cell_at(self, e):
        z8, (w, h) = 8 * self.ed.zoom(), self.size()
        cx, cy = e.x // z8, e.y // z8
        return (cx, cy) if 0 <= cx < w and 0 <= cy < h else None

    def press(self, e, b):
        self.focus_set()
        self.last, self.pending = None, True
        if self.ed.mode.get() == 'tiles' and b == 1:
            pos = self.cell_at(e)
            if pos:
                self.ed.pick(*pos)
            return
        self.drag(e, b)

    def touch(self):
        if self.pending:
            self.app.hist.checkpoint(self.ed.owner)
            self.pending = False

    def drag(self, e, b):
        rows, ts = self.ed.rows(), self.ed.tiles()
        if self.ed.mode.get() == 'tiles':
            pos = self.cell_at(e)
            if b != 0 or not pos or pos == self.last:
                return
            self.last = self.ed.cur = self.ed.st['cell'] = pos
            c, (t, a) = rows[pos[1]][pos[0]], self.ed.brush()
            if 0 <= t < len(ts) and [t, a] != c[:2]:
                self.touch()
                c[0], c[1] = t, a
                self.zi.put(pos[0] * 8, pos[1] * 8, 8, 8, cell_px(c, ts, self.ed.colors()))
                self.ed.cells_changed()
            self.overlay()
            return
        z, (w, h) = self.ed.zoom(), self.size()
        p = (e.x // z, e.y // z)
        pts, self.last = (line(self.last, p) if self.last else [p]), p
        v, hit = self.app.pen[b], set()
        for x, y in pts:
            cx, cy = x // 8, y // 8
            if not (0 <= cx < w and 0 <= cy < h):
                continue
            c = rows[cy][cx]
            if not 0 <= c[0] < len(ts):
                continue
            sx, sy = (7 - x % 8 if c[1] & FLIP_X else x % 8), (7 - y % 8 if c[1] & FLIP_Y else y % 8)
            tile = ts[c[0]]
            if tile[sy * 8 + sx] != v:
                self.touch()
                tile[sy * 8 + sx] = v
                hit.add(c[0])
        for t in hit:
            self.ed.panel.pixels(t)

    def hover(self, e):
        pos = self.cell_at(e)
        if not pos:
            return
        c = self.ed.rows()[pos[1]][pos[0]]
        a = c[1]
        flips = ' '.join(n for n, f in (('flip X', FLIP_X), ('flip Y', FLIP_Y), ('priority', PRIORITY)) if a & f)
        self.app.status('cell %d,%d   tile %d   palette %d   %s' % (pos[0], pos[1], c[0], a & 7, flips))


class CellEditor(Editor):
    """Shared by the picture and metatile editors: the cells, a brush, and the tile panel."""

    def __init__(self, master, app, loc, owner, kind, palette_doc, zoom):
        super().__init__(master, app, loc)
        z, st = app.z, self.st
        self.owner, self.kind, self.doc = owner, kind, palette_doc
        self.mode = tk.StringVar(value=st.get('mode', 'tiles'))
        self.grid_on = tk.BooleanVar(value=st.get('grid', False))
        self.uses_on = tk.BooleanVar(value=st.get('uses', True))
        self.bfx, self.bfy, self.bpri = tk.BooleanVar(), tk.BooleanVar(), tk.BooleanVar()
        self.bpal = tk.StringVar(value='0')
        self.zoom_var = tk.StringVar(value=str(st.get('zoom', app.z(zoom))))
        self.cur = st.get('cell')
        self.header = ttk.Frame(self)
        self.header.grid(row=0, column=0, columnspan=2, sticky='ew', pady=(0, z(8)))
        self.left = ttk.Frame(self)
        self.left.grid(row=1, column=0, sticky='nsew')
        right = ttk.Frame(self)
        right.grid(row=1, column=1, sticky='ns', padx=(z(14), 0))
        self.columnconfigure(0, weight=1)
        self.rowconfigure(1, weight=1)
        bar = ttk.Frame(self.left)
