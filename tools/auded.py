#!/usr/bin/env python3
"""auded: a folder of game sound (a sound project) - the editor, and the export to Roswell Color C data.

The sound project is the source of the game's music and sound effects: this edits, plays, checks and exports
it. By default it is the project's assets/ folder (the folder above tools/, shared with the art project,
whose files have other names), and it exports to data/music/ and data/sounds/. Standard library only
(tkinter for the editor). It plays what it shows the way the console does: the preview is a copy of the
console's 4 channels, sample for sample.

    python tools/auded.py [sound dir]                      the editor
    python tools/auded.py export [sound dir] [C out dir]   export to C       default C out dir: the project's
    python tools/auded.py check [sound dir]                list the problems that would stop an export
    python tools/auded.py new [sound dir] [C out dir]      make a blank sound project there
    python tools/auded.py wav [sound dir] <tune> <file>    write a song or sound effect to a .wav file

The sound dir defaults to assets/. The editor opens the sound project in that folder; a folder that does
not exist yet is made, with a blank sound project in it. File > Open folder switches to another (typed, or
picked with Browse). Each project keeps the folder it exports to in sound.json ("export", relative to the
project; a new one exports to data beside it). The export writes two folders in it: music/ (the songs)
and sounds/ (the sound effects, the waves, the driver and sound.h). File > Export folder changes it; a C
out dir given to `export` is used for that run only (music/ and sounds/ go in it the same way).
File > Save writes the project and File > Export C writes the C, the way `export` does.
Help > Keys lists the controls. export, check and wav need no display or Tk.

The layout of a sound project (all JSON):
  sound.json           {"songs": [names], "sfx": [names]}, in export order, and "export": the folder
                       Export C writes, relative to this one
  waves.json           {"waves": [{"name", "samples": 32 hex digits}]}: the shapes the wave channel plays
  instruments.json     {"instruments": [instrument]}
  songs/<name>.json    {"name", "speed", "loop", "rows": [row]}
  sfx/<name>.json      {"name", "speed", "rows": [row]}: a sound effect; it plays once

  instrument  {"name", "type": "pulse" | "wave" | "noise", then the fields of its type:
                pulse:  "duty" 12|25|50|75, "volume" 0..15, "env_dir" "down"|"up", "env_pace" 0..7, "length" 0..64,
                        "sweep_pace" 0..7, "sweep_dir" "up"|"down", "sweep_shift" 0..7 (the sweep works on CH1 only)
                wave:   "wave" (a wave's name), "level" 100|50|25|0, "length" 0..256
                noise:  "width" 15|7, "volume", "env_dir", "env_pace", "length" 0..64}
              These are the console's rc_voice fields (rc_dev.h section 9). length 0 plays until stopped,
              n plays n/256 s; env_pace n changes the volume by 1 every n/64 s; sweep_pace n changes the
              period by period >> sweep_shift every n/128 s.
  speed       frames a row lasts (60 frames = 1 s), 1..60, may have a fraction: row r starts on frame
              round(r * speed). At 4 rows a beat that is 900 / speed BPM.
  loop        the row a song goes back to at its end, or null to stop there.
  row         4 cells, for CH1 (pulse with sweep), CH2 (pulse), CH3 (wave), CH4 (noise).
  cell        "" nothing new: the channel keeps doing what it was doing
              "off" stop the channel
              "C-4 lead 12"  play a note: note name, instrument (optional: the channel's last one) and
                             volume 0..15 (optional: the instrument's). Notes run C-0..B-8, A-4 = 440 Hz;
                             a sharp is "C#4". On CH3 the volume picks the wave level (0 mute, 1..5 25%,
                             6..11 50%, 12..15 100%). On CH4 the note picks the noise clock (the note's
                             frequency x 128, the nearest the console has).
              "~C-4"         slide: change the pitch of the note playing without restarting it (CH1..CH3).

Export: one rc_music per song and per sound effect (rc_dev.h section 11), and a small driver,
sound_driver.c, that plays a song and sound effects together: a sound effect takes the channels
it uses from the song until it ends.
"""
