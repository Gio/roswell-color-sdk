        self.cv.bind('<B1-Motion>', self.drag)
        t = ttk.Frame(self)
        t.pack(anchor='w', pady=z(8))
        for name in ('sine', 'triangle', 'saw', 'square'):
            ttk.Button(t, text=name.capitalize(), command=lambda n=name: self.put(list(WAVE_SHAPES[n]))).pack(side='left', padx=1)
        ttk.Separator(t, orient='vertical').pack(side='left', fill='y', padx=z(6))
        for name, fn in (('Invert', lambda s: [15 - v for v in s]), ('Reverse', lambda s: s[::-1]),
                         ('Shift left', lambda s: s[1:] + s[:1]), ('Shift right', lambda s: s[-1:] + s[:-1]),
                         ('Smooth', lambda s: [round((s[k - 1] + 2 * s[k] + s[(k + 1) % 32]) / 4.0) for k in range(32)])):
            ttk.Button(t, text=name, command=lambda fn=fn: self.put(fn(self.samples()))).pack(side='left', padx=1)
