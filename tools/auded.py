def rel_path(path, start):
    """path relative to start, with / between parts (absolute when they are on different drives)."""
    try:
        return Path(os.path.relpath(Path(path).resolve(), Path(start).resolve())).as_posix()
    except ValueError:
        return Path(path).resolve().as_posix()


def source_name(root, out):
    """How the generated C names the project it came from: its path from the folder it shares with out."""
    root, out = Path(root).resolve(), Path(out).resolve()
    try:
        common = Path(os.path.commonpath([root, out]))
    except ValueError:
        return root.name
    return root.name if root == common else rel_path(root, common)


# ================================================================ JSON layout
def has_obj(v):
    return isinstance(v, dict) or (isinstance(v, list) and any(has_obj(x) for x in v))


def fmt(v, ind=0):
    """A container goes on one line when it holds no objects and fits in 160 columns (so a song is a row a
    line), so a save rewrites only what changed."""
    c = dumps(v)
    if not isinstance(v, (list, dict)) or not v or (not has_obj(v) and ind + len(c) <= 160):
        return c
    pad, end = ' ' * (ind + 2), '\n' + ' ' * ind
    if isinstance(v, list):
        return '[\n' + ',\n'.join(pad + fmt(x, ind + 2) for x in v) + end + ']'
    return '{\n' + ',\n'.join(pad + dumps(k) + ': ' + fmt(x, ind + 2) for k, x in v.items()) + end + '}'


def dumps(v):
    """Compact JSON, UTF-8, with the characters that do not show written as \\uNNNN."""
    return re.sub('[\x7f-\xa0\xad]', lambda m: '\\u%04x' % ord(m.group()),
                  json.dumps(v, separators=(',', ':'), ensure_ascii=False))


def write_text(path, text):
    """Writes text to path (by way of a temp file) unless it already holds it. True when it wrote."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding='utf-8') == text:
        return False
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(text, encoding='utf-8', newline='\n')
    os.replace(tmp, path)
    return True


# ================================================================ notes
def note_name(n):
    return NOTE_NAMES[n % 12] + str(n // 12)


def parse_note(s):
    """'C-4' / 'C#4' / 'c4' / 'Db4' -> note number, or None."""
    m = re.match(r'^([A-Ga-g])([-#b]?)(\d)$', s)
    if not m:
        return None
    n = 'C D EF G A B'.index(m.group(1).upper()) + {'': 0, '-': 0, '#': 1, 'b': -1}[m.group(2)] + 12 * int(m.group(3))
    return n if 0 <= n <= NOTE_MAX else None


def note_hz(n):
    return 440.0 * 2.0 ** ((n - 57) / 12.0)


def tone_period(n, kind):
    """The rc_voice period that plays note n on a pulse (CH1, CH2) or the wave channel (CH3)."""
    top = 131072.0 if kind == 'pulse' else 65536.0
    return max(0, min(2047, int(round(2048 - top / note_hz(n)))))


def noise_clock(shift, divisor):
    return 262144.0 / ((divisor or 0.5) * 2 ** shift)


@functools.lru_cache(maxsize=None)
def noise_setting(n):
    """(noise_shift, noise_divisor) whose LFSR clock is nearest note n's frequency x 128."""
    want = math.log(note_hz(n) * NOISE_CLOCK_PER_HZ)
    return min(((s, d) for s in range(14) for d in range(8)), key=lambda sd: (abs(math.log(noise_clock(*sd)) - want), sd))


# ================================================================ cells
def parse_cell(text):
    """A cell's text -> None (empty), ('off',), ('note', n, inst or None, vol or None) or ('slide', n).
    Raises ValueError with the reason when it is not a cell."""
    t = text.split()
    if not t:
        return None
    if t[0].lower() == 'off':
        if len(t) > 1:
            raise ValueError('"off" takes nothing after it')
        return ('off',)
    if t[0].startswith('~'):
        n = parse_note(t[0][1:])
        if n is None or len(t) > 1:
            raise ValueError('a slide is ~ and a note, like ~C-4')
        return ('slide', n)
    n = parse_note(t[0])
    if n is None:
        raise ValueError('%r is not a note (C-0..B-8, like C-4 or F#3)' % t[0])
    inst = vol = None
    for x in t[1:]:
        if x.isdigit() and vol is None:
            vol = int(x)
            if vol > 15:
                raise ValueError('a volume is 0..15')
        elif NAME_RE.match(x) and inst is None and vol is None:
            inst = x
        else:
            raise ValueError('a note is followed by an instrument name and a volume, like C-4 lead 12')
    return ('note', n, inst, vol)


def cell_text(c):
    if c is None:
        return ''
    if c[0] == 'off':
        return 'off'
    if c[0] == 'slide':
        return '~' + note_name(c[1])
    return ' '.join([note_name(c[1])] + ([c[2]] if c[2] else []) + ([str(c[3])] if c[3] is not None else []))


def cell_or_none(text):
    try:
        return parse_cell(text)
    except ValueError:
        return None


# ================================================================ waves and instruments
WAVE_SHAPES = {
    'sine': [round(7.5 + 7.5 * math.sin(2 * math.pi * (i + 0.5) / 32)) for i in range(32)],
    'triangle': [i if i < 16 else 31 - i for i in range(32)],
    'saw': [i // 2 for i in range(32)],
    'square': [15] * 16 + [0] * 16,
}


def wave_text(samples):
    return ''.join('%x' % v for v in samples)


def wave_samples(text):
    return [int(c, 16) for c in text]


def wave_bytes(samples):
    return bytes(samples[i] << 4 | samples[i + 1] for i in range(0, 32, 2))


INST_FIELDS = {
    'pulse': ('duty', 'volume', 'env_dir', 'env_pace', 'length', 'sweep_pace', 'sweep_dir', 'sweep_shift'),
    'wave': ('wave', 'level', 'length'),
    'noise': ('width', 'volume', 'env_dir', 'env_pace', 'length'),
}
INST_DEFAULTS = {'duty': 50, 'volume': 15, 'env_dir': 'down', 'env_pace': 0, 'length': 0, 'sweep_pace': 0,
                 'sweep_dir': 'down', 'sweep_shift': 0, 'wave': '', 'level': 100, 'width': 15}


def blank_instrument(name, kind, wave=''):
    d = {'name': name, 'type': kind}
    for k in INST_FIELDS[kind]:
        d[k] = INST_DEFAULTS[k]
    if kind == 'wave':
        d['wave'] = wave
    return d


def norm_instrument(d):
    """The instrument with every field of its type, so the editor and the export can rely on them."""
    kind = d.get('type', 'pulse')
    out = {'name': d['name'], 'type': kind}
    for k in INST_FIELDS.get(kind, ()):
        out[k] = d.get(k, INST_DEFAULTS[k])
    out.update((k, v) for k, v in d.items() if k not in out and k not in INST_DEFAULTS)
    return out


def change_type(inst, kind, wave=''):
    """Turns inst into a kind instrument in place, keeping the fields both types have."""
    old = dict(inst)
    inst.clear()
    inst.update(blank_instrument(old['name'], kind, wave))
    for k in INST_FIELDS[kind]:
        if k in old and k != 'wave':
            inst[k] = old[k]


def wave_level_of(vol):
    """A cell volume on CH3 -> RC_WAVE_ level number (0 mute, 1 = 100%, 2 = 50%, 3 = 25%)."""
    return 0 if vol == 0 else 3 if vol <= 5 else 2 if vol <= 11 else 1


def voice(inst, n, vol, ch, wave_ok=True):
    """The rc_voice (a dict of its nonzero fields, enum values as numbers) that plays note n with inst on
    channel ch (0..3), at cell volume vol (None: the instrument's)."""
    kind, v = inst['type'], {}

    def put(k, x):
        if x:
            v[k] = x
    put('length', inst['length'])
    if kind == 'wave':
        put('period', tone_period(n, 'wave'))
        put('wave_level', wave_level_of(vol) if vol is not None else LEVELS.index(inst['level']))
        return v
    put('volume', inst['volume'] if vol is None else vol)
    put('env_dir', 1 if inst['env_dir'] == 'up' else 0)
    put('env_pace', inst['env_pace'])
    if kind == 'pulse':
        put('period', tone_period(n, 'pulse'))
        put('duty', DUTIES.index(inst['duty']))
        if ch == 0 and inst['sweep_shift'] and inst['sweep_pace']:
            put('sweep_pace', inst['sweep_pace'])
            put('sweep_dir', 1 if inst['sweep_dir'] == 'down' else 0)
            put('sweep_shift', inst['sweep_shift'])
    else:
        s, d = noise_setting(n)
        put('noise_shift', s)
        put('noise_divisor', d)
        put('noise_width', 1 if inst['width'] == 7 else 0)
    return v


# ================================================================ the project
class Project:
    """A sound project in memory."""

    def __init__(self, root):
        self.root = Path(root)
        self.files = set()
        self.load()

    @classmethod
    def create(cls, root, out=None):
        """Writes a blank sound project to root (made if missing), which must not have one yet: a triangle
        wave, one instrument for each channel and an empty song. out is where it exports to (default:
        default_export). Returns it."""
        root = Path(root)
        if (root / 'sound.json').exists():
            raise FileExistsError('%s already has a sound project (sound.json)' % root)
        p = cls.__new__(cls)
        p.root, p.files = root, set()
        p.settings = {'export': rel_path(out or default_export(root), root)}
        p.waves = [{'name': 'triangle', 'samples': wave_text(WAVE_SHAPES['triangle'])}]
        p.instruments = [blank_instrument('lead', 'pulse'), blank_instrument('bass', 'wave', 'triangle'),
                         dict(blank_instrument('drum', 'noise'), env_pace=1)]
        p.instruments[0]['duty'] = 25
        p.songs = [blank_tune('song', 8, 64, loop=0)]
        p.sfx = []
        p.save()
        return p

    def _read(self, rel):
        self.files.add(rel)
        with open(self.root / rel, encoding='utf-8') as f:
            return json.load(f)

    def load(self):
        self.files = set()
        idx = self._read('sound.json')
        self.settings = {'export': idx.get('export') or rel_path(default_export(self.root), self.root)}
        self.waves = self._read('waves.json')['waves'] if (self.root / 'waves.json').exists() else []
        self.instruments = [norm_instrument(d) for d in self._read('instruments.json')['instruments']] \
            if (self.root / 'instruments.json').exists() else []
        self.songs = [self._tune('songs/%s.json' % n, True) for n in idx.get('songs', [])]
        self.sfx = [self._tune('sfx/%s.json' % n, False) for n in idx.get('sfx', [])]

    def _tune(self, rel, song):
        d = self._read(rel)
        d.setdefault('speed', 8 if song else 1)
        d['rows'] = [list(r) + [''] * (4 - len(r)) for r in d.get('rows', [])]
        if song:
            d.setdefault('loop', 0)
        else:
            d.pop('loop', None)
        return d

    # ---- saving
    def documents(self):
        yield 'sound.json', {'songs': [t['name'] for t in self.songs], 'sfx': [t['name'] for t in self.sfx],
                             'export': self.settings['export']}
        yield 'waves.json', {'waves': self.waves}
        yield 'instruments.json', {'instruments': self.instruments}
        for folder, tunes in (('songs', self.songs), ('sfx', self.sfx)):
            for t in tunes:
                d = {k: t[k] for k in ('name', 'speed', 'loop') if k in t}
                d.update((k, v) for k, v in t.items() if k not in d and k != 'rows')
                d['rows'] = t['rows']
                yield '%s/%s.json' % (folder, t['name']), d

    def save(self):
        """Writes every file whose text changed, and removes the file of a song or sound effect that was
        renamed or deleted (only files this project loaded or saved)."""
        written, now = 0, set()
        for rel, v in self.documents():
            written += write_text(self.root / rel, fmt(v) + '\n')
            now.add(rel)
        lower = {rel.lower(): rel for rel in now}
        for old in sorted(self.files - now):
            f = self.root / old
            if not f.exists():
                continue
            new = lower.get(old.lower())
            if new and os.path.samefile(f, self.root / new):
                os.replace(f, self.root / new)  # renamed in case only, on a case-blind file system
            else:
                f.unlink()
            written += 1
        self.files = now
        return written

    def export_dir(self):
        """Where the C goes: the folder sound.json names, relative to the project."""
        return Path(os.path.normpath(self.root / self.settings['export']))

    # ---- lookups
    def instrument(self, name):
        return next((i for i in self.instruments if i['name'] == name), None)

    def wave(self, name):
        return next((w for w in self.waves if w['name'] == name), None)

    def tunes(self):
        """(kind, tune) for every song and sound effect."""
        return [('song', t) for t in self.songs] + [('sfx', t) for t in self.sfx]


def blank_tune(name, speed, rows, loop=None):
    t = {'name': name, 'speed': speed}
    if loop is not None:
        t['loop'] = loop
    t['rows'] = [list(BLANK_ROW) for _ in range(rows)]
    return t


def instrument_users(proj, name):
    """[(tune, row, channel)] of every note that names instrument name."""
    out = []
    for _, t in proj.tunes():
        for r, row in enumerate(t['rows']):
            for ch, text in enumerate(row):
                c = cell_or_none(text)
                if c and c[0] == 'note' and c[2] == name:
                    out.append((t, r, ch))
    return out


def rename_instrument_uses(proj, old, new):
    for t, r, ch in instrument_users(proj, old):
        c = parse_cell(t['rows'][r][ch])
        t['rows'][r][ch] = cell_text((c[0], c[1], new, c[3]))


# ================================================================ tunes -> events
def row_frame(r, speed):
    return int(math.floor(r * speed + 0.5))


def tune_events(proj, tune, problems=None):
    """The rc_music of a song or sound effect: (events, frame_count, loop_frame). An event is a dict:
    frame, ch (0..3), op ('play', 'stop', 'period' or 'wave'), and voice / value / wave (a name).
    Cells that cannot play are left out, and added to problems (a list), when given, as (row, channel, why)."""
    speed, rows = tune['speed'], tune['rows']
    loop = tune.get('loop')
    ev, last_inst, loaded = [], [None] * 4, None

    def bad(r, ch, why):
        if problems is not None:
            problems.append((r, ch, why))
    for r, row in enumerate(rows):
        f = row_frame(r, speed)
        if r == loop:
            loaded = None   # coming round again, the wave in Wave RAM may be a later one
        for ch in range(4):
            try:
                c = parse_cell(row[ch])
            except ValueError as ex:
                bad(r, ch, str(ex))
                continue
            if c is None:
                continue
            if c[0] == 'off':
                ev.append({'frame': f, 'ch': ch, 'op': 'stop'})
                continue
            kind = CH_TYPE[ch]
            lo, hi = NOTE_RANGE[kind]
            if not lo <= c[1] <= hi:
                bad(r, ch, '%s is out of range: %s plays %s..%s' % (note_name(c[1]), CHANNELS[ch], note_name(lo), note_name(hi)))
                continue
            if c[0] == 'slide':
                if ch == 3:
                    bad(r, ch, 'the noise channel cannot slide')
                else:
                    ev.append({'frame': f, 'ch': ch, 'op': 'period', 'value': tone_period(c[1], kind)})
                continue
            name = c[2] or last_inst[ch]
            inst = proj.instrument(name) if name else None
            if inst is None:
                bad(r, ch, 'no instrument %s' % name if name else 'the note has no instrument (and none came before it)')
                continue
            if inst['type'] != kind:
                bad(r, ch, '%s is a %s instrument; %s plays %s instruments' % (name, inst['type'], CHANNELS[ch], kind))
                continue
            last_inst[ch] = name
            if kind == 'wave':
                w = proj.wave(inst['wave'])
                if w is None:
                    bad(r, ch, 'instrument %s has no wave' % name)
                    continue
                if loaded != w['name']:
                    ev.append({'frame': f, 'ch': ch, 'op': 'wave', 'wave': w['name']})
                    loaded = w['name']
            ev.append({'frame': f, 'ch': ch, 'op': 'play', 'voice': voice(inst, c[1], c[3], ch)})
    frames = max(1, row_frame(len(rows), speed))
    lf = row_frame(loop, speed) if loop is not None and 0 <= loop < len(rows) else -1
    return ev, frames, lf


def channels_used(events):
    return sorted({e['ch'] for e in events})


# ================================================================ checks
def check(proj):
    """Everything that would stop an export, as a list of messages."""
    bad = []
    names = {}
    for kind, items in (('wave', proj.waves), ('instrument', proj.instruments), ('song', proj.songs),
                        ('sound effect', proj.sfx)):
        seen = {}
        for x in items:
            n = x.get('name', '')
            if not NAME_RE.match(n):
                bad.append('%s %r: a name is letters, digits and _, and starts with a letter' % (kind, n))
            elif cid(n) in seen:
                bad.append('%ss %s and %s have the same C name' % (kind, seen[cid(n)], n))
            seen[cid(n)] = n
        names[kind] = seen
    for w in proj.waves:
        if not re.match(r'^[0-9a-fA-F]{32}$', w.get('samples', '')):
            bad.append('wave %s: samples are 32 hex digits' % w['name'])
    for i in proj.instruments:
        n, kind = i['name'], i['type']
        if kind not in TYPES:
            bad.append('instrument %s: type is pulse, wave or noise' % n)
            continue

        def rng(k, lo, hi):
            v = i.get(k)
            if not isinstance(v, int) or isinstance(v, bool) or not lo <= v <= hi:
                bad.append('instrument %s: %s is %d..%d' % (n, k, lo, hi))
        rng('length', 0, MAX_LENGTH[kind])
        if kind != 'wave':
            rng('volume', 0, 15)
            rng('env_pace', 0, 7)
            if i['env_dir'] not in ('down', 'up'):
                bad.append('instrument %s: env_dir is down or up' % n)
        if kind == 'pulse':
            if i['duty'] not in DUTIES:
                bad.append('instrument %s: duty is 12, 25, 50 or 75' % n)
            rng('sweep_pace', 0, 7)
            rng('sweep_shift', 0, 7)
            if i['sweep_dir'] not in ('down', 'up'):
                bad.append('instrument %s: sweep_dir is down or up' % n)
        if kind == 'wave':
            if i['level'] not in LEVELS:
                bad.append('instrument %s: level is 100, 50, 25 or 0' % n)
            if proj.wave(i['wave']) is None:
                bad.append('instrument %s: there is no wave %r' % (n, i['wave']))
        if kind == 'noise' and i['width'] not in (15, 7):
            bad.append('instrument %s: width is 15 or 7' % n)
    for kind, t in proj.tunes():
        what = 'song' if kind == 'song' else 'sound effect'
        if cid(t['name']) in RESERVED_TUNES:
            bad.append('%s %s: a %s cannot be called that, its C name would clash' % (what, t['name'], what))
        sp = t.get('speed')
        if not isinstance(sp, (int, float)) or isinstance(sp, bool) or not 1 <= sp <= MAX_SPEED:
            bad.append('%s %s: speed is 1..%d frames a row' % (what, t['name'], MAX_SPEED))
            continue
        if not t['rows']:
            bad.append('%s %s has no rows' % (what, t['name']))
        if len(t['rows']) > MAX_ROWS:
            bad.append('%s %s has more than %d rows' % (what, t['name'], MAX_ROWS))
        if kind == 'song' and t.get('loop') is not None and not (isinstance(t['loop'], int) and 0 <= t['loop'] < len(t['rows'])):
            bad.append('song %s: loop is a row number (0..%d) or null' % (t['name'], len(t['rows']) - 1))
        problems = []
        tune_events(proj, t, problems)
        bad += ['%s %s row %d %s: %s' % (what, t['name'], r, CHANNELS[ch], why) for r, ch, why in problems]
    return bad


