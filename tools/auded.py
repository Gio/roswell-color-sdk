class Field(ttk.Entry):
    """An entry that applies its text on Return or when it loses focus. apply(text) returns an error
    message, or None when the change was made."""

    def __init__(self, master, value, apply, width=16):
        self.var = tk.StringVar(value=value)
        super().__init__(master, textvariable=self.var, width=width)
        self.value, self.apply = value, apply
        self.bind('<Return>', self.commit)
        self.bind('<FocusOut>', self.commit)
        self.bind('<Escape>', lambda e: self.var.set(self.value))

    def set_value(self, v):
        self.value = v
        self.var.set(v)

    def commit(self, e=None):
        v = self.var.get()
        if v == self.value:
            return
        err = self.apply(v)
        if err:
            self.var.set(self.value)
            messagebox.showerror('Not changed', err)
        else:
            self.value = self.var.get()


