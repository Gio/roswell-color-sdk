# ================================================================ a song or sound effect: the grid
class TrackerGrid(tk.Canvas):
    """The rows of a song or sound effect, drawn only where they show. The cursor is (row, channel, part)
    with part 0 the note, 1 the instrument, 2 the volume."""
    PARTS = ((0, 3), (4, 8), (13, 2))   # character offset and width of each part of a cell
    CELL = 15
    GAP = 3

    def __init__(self, master, ed):
        super().__init__(master, bg=GRID_BG, highlightthickness=2, highlightcolor=GRID_CUR, highlightbackground=GRID_BG,
                         takefocus=1)
        self.ed, self.app, self.t = ed, ed.app, ed.t
        self.font = ed.app.mono
        self.cwid = self.font.measure('0')
        self.lh = self.font.metrics('linespace') + ed.app.z(3)
        self.x0 = ed.app.z(6)
        st = ed.st
        self.row, self.ch, self.part = st.get('cursor', (0, 0, 0))
        self.top = st.get('top', 0)
        self.anchor, self.sel, self.playrow, self.bad = None, st.get('sel'), None, {}
        self.sb = None
        self.entry = None
        self.configure(width=self.x0 * 2 + (5 + 4 * (self.CELL + self.GAP)) * self.cwid)
        self.bind('<Configure>', lambda e: self.redraw())
        self.bind('<Button-1>', self.click)
        self.bind('<B1-Motion>', self.drag)
        self.bind('<Double-Button-1>', lambda e: self.edit_text())
        for ev in ('<Tab>', '<Shift-Tab>', '<ISO_Left_Tab>'):   # before Tk's own Tab, which moves the focus
            self.bind(ev, lambda e: (self.key(e), 'break')[1])
        for ev in ('<MouseWheel>', '<Button-4>', '<Button-5>'):
            self.bind(ev, self.wheel)
        self.find_problems()

    # ---- geometry
    def visible(self):
        return max(1, (self.winfo_height() - self.lh - 4) // self.lh)

    def cell_x(self, ch, part=0):
        return self.x0 + (5 + ch * (self.CELL + self.GAP) + self.PARTS[part][0]) * self.cwid

    def at(self, e):
        """(row, channel, part) under a mouse event."""
        r = self.top + max(0, (e.y - self.lh - 2)) // self.lh
        cx = (e.x - self.x0) / float(self.cwid) - 5
        ch = max(0, min(3, int(cx // (self.CELL + self.GAP))))
        off = cx - ch * (self.CELL + self.GAP)
        part = 0 if off < 4 else 1 if off < 13 else 2
        return max(0, min(len(self.t['rows']) - 1, r)), ch, part

    # ---- drawing
    def find_problems(self):
        probs = []
        tune_events(self.app.proj, self.t, probs)
        self.bad = {(r, ch): why for r, ch, why in probs}

    def save_state(self):
        self.ed.st.update(cursor=(self.row, self.ch, self.part), top=self.top, sel=self.sel)

    def redraw(self):
        if not self.winfo_exists():
            return
        self.delete('all')
        rows, lh, f, cw = self.t['rows'], self.lh, self.font, self.cwid
        vis = self.visible()
        self.top = max(0, min(self.top, len(rows) - vis))
        width = max(self.winfo_width(), self.cell_x(4))
        loop = self.t.get('loop')
        sel = self.sel_box()
        for k, name in enumerate(CHANNELS):
            self.create_text(self.cell_x(k), 2, anchor='nw', font=f, fill=GRID_DIM, text='%s %s' % (name, CH_TYPE[k]))
        for r in range(self.top, min(len(rows), self.top + vis)):
            y = lh + 2 + (r - self.top) * lh
            bg = GRID_PLAY if r == self.playrow else GRID_BAR if r % 16 == 0 else GRID_BEAT if r % 4 == 0 else None
            if bg:
                self.create_rectangle(0, y, width, y + lh, fill=bg, outline='')
            if sel and sel[0] <= r <= sel[2]:
                self.create_rectangle(self.cell_x(sel[1]) - cw // 2, y, self.cell_x(sel[3]) + self.CELL * cw + cw // 2, y + lh,
                                      fill=GRID_SEL, outline='')
            self.create_text(self.x0, y + 1, anchor='nw', font=f, fill=GRID_LOOP if r == loop else GRID_DIM,
                             text=('%3d' % r) + ('>' if r == loop else ''))
            for ch in range(4):
                self.draw_cell(r, ch, y)
        if self.top <= self.row < self.top + vis:
            y = lh + 2 + (self.row - self.top) * lh
            x = self.cell_x(self.ch, self.part)
            self.create_rectangle(x - 2, y, x + self.PARTS[self.part][1] * cw + 2, y + lh - 1, outline=GRID_CUR, width=2)
        if self.sb is not None:
            n = float(max(1, len(rows)))
            self.sb.set(self.top / n, min(1.0, (self.top + vis) / n))

    def draw_cell(self, r, ch, y):
        text = self.t['rows'][r][ch]
        f, x = self.font, self.cell_x(ch)
        bad = (r, ch) in self.bad
        try:
            c = parse_cell(text)
        except ValueError:
            self.create_text(x, y + 1, anchor='nw', font=f, fill=GRID_BAD, text=text[:self.CELL])
            return
        if c is None:
            self.create_text(x, y + 1, anchor='nw', font=f, fill=GRID_DIM, text='...  ........ ..')
            return
        if c[0] == 'off':
            self.create_text(x, y + 1, anchor='nw', font=f, fill=GRID_BAD if bad else GRID_OFF, text='off')
            return
        if c[0] == 'slide':
            self.create_text(x, y + 1, anchor='nw', font=f, fill=GRID_BAD if bad else GRID_SLIDE, text=note_name(c[1]) + ' ~slide')
            return
        self.create_text(x, y + 1, anchor='nw', font=f, fill=GRID_BAD if bad else GRID_TEXT, text=note_name(c[1]))
        inst = c[2] or ''
        self.create_text(self.cell_x(ch, 1), y + 1, anchor='nw', font=f, fill=GRID_BAD if bad else GRID_INST if inst else GRID_DIM,
                         text=(inst[:7] + '~' if len(inst) > 8 else inst) or '........')
        self.create_text(self.cell_x(ch, 2), y + 1, anchor='nw', font=f, fill=GRID_VOL if c[3] is not None else GRID_DIM,
                         text='%2d' % c[3] if c[3] is not None else '..')

    def sel_box(self):
        if not self.sel:
            return None
        (r0, c0), (r1, c1) = self.sel
        return min(r0, r1), min(c0, c1), max(r0, r1), max(c0, c1)

    def show_cursor(self):
        vis = self.visible()
        if self.row < self.top:
            self.top = self.row
        elif self.row >= self.top + vis:
            self.top = self.row - vis + 1
        self.save_state()
        self.redraw()
        self.ed.cursor_moved()

    # ---- mouse
    def click(self, e):
        self.focus_set()
        self.commit_entry()
        self.row, self.ch, self.part = self.at(e)
        self.anchor, self.sel = (self.row, self.ch), None
        self.show_cursor()

    def drag(self, e):
        r, ch, _ = self.at(e)
        if self.anchor and (r, ch) != self.anchor:
            self.sel = (self.anchor, (r, ch))
        self.row, self.ch = r, ch
        self.show_cursor()

    def wheel(self, e):
        d = -1 if (e.num == 4 or getattr(e, 'delta', 0) > 0) else 1
        self.scroll(d * 4)

    def scroll(self, n):
        self.top = max(0, min(len(self.t['rows']) - self.visible(), self.top + n))
        self.save_state()
        self.redraw()

    def yview(self, *a):
        """The scrollbar's command."""
        rows = len(self.t['rows'])
        if a[0] == 'moveto':
            self.top = int(float(a[1]) * rows)
        elif a[0] == 'scroll':
            self.top += int(a[1]) * (self.visible() if a[2] == 'pages' else 1)
        self.scroll(0)

    # ---- keys
    def key(self, e):
        """Handles a key; True when it did something."""
        if self.entry is not None:
            return False
        ks, ch = e.keysym, (e.char or '')
        ctrl, shift = bool(e.state & 0x4), bool(e.state & 0x1)
        rows = len(self.t['rows'])
        moves = {'Up': (-1, 0), 'Down': (1, 0), 'Prior': (-16, 0), 'Next': (16, 0)}
        if ctrl:
            low = ks.lower()
            if low == 'c':
                return self.copy()
            if low == 'x':
                return self.copy() and self.clear()
            if low == 'v':
                return self.paste()
            if low == 'a':
                self.sel = ((0, 0), (rows - 1, 3))
                self.redraw()
                return True
            if ks in ('Up', 'Down'):
                return self.transpose((12 if shift else 1) * (1 if ks == 'Up' else -1))
            if ks == 'Delete':
                return self.delete_row()
            return False
        if ks in moves or ks in ('Home', 'End', 'Left', 'Right', 'Tab', 'ISO_Left_Tab'):
            if shift and ks not in ('Tab', 'ISO_Left_Tab'):
                if not self.sel:
                    self.sel = ((self.row, self.ch), (self.row, self.ch))
            elif ks not in ('Tab', 'ISO_Left_Tab'):
                self.sel = None
            if ks in moves:
                self.row = max(0, min(rows - 1, self.row + moves[ks][0]))
            elif ks == 'Home':
                self.row = 0
            elif ks == 'End':
                self.row = rows - 1
            elif ks == 'Tab' and not shift:
                self.ch, self.part = (self.ch + 1) % 4, 0
            elif ks in ('ISO_Left_Tab', 'Tab'):
                self.ch, self.part = (self.ch - 1) % 4, 0
            elif ks == 'Left':
                if shift:
                    self.ch = max(0, self.ch - 1)
                elif self.part:
                    self.part -= 1
                elif self.ch:
                    self.ch, self.part = self.ch - 1, 2
            elif ks == 'Right':
                if shift:
                    self.ch = min(3, self.ch + 1)
                elif self.part < 2:
                    self.part += 1
                elif self.ch < 3:
                    self.ch, self.part = self.ch + 1, 0
            if self.sel:
                self.sel = (self.sel[0], (self.row, self.ch))
            self.show_cursor()
            return True
        if ks == 'Escape':
            self.sel = None
            self.redraw()
            return True
        if ks == 'Delete':
            return self.clear()
        if ks == 'Insert':
            return self.insert_row()
        if ks == 'space':
            self.ed.toggle_play()
            return True
        if ks == 'F5':
            self.ed.play(0)
            return True
        if ch in ('/', '*') or ks in ('KP_Divide', 'KP_Multiply'):
            self.ed.change_octave(-1 if ch == '/' or ks == 'KP_Divide' else 1)
            return True
        if self.part == 0:
            if ks == 'Return':
                self.edit_text()
                return True
            if ch == '1':
                return self.put_cell('off')
            if ch in ('~', '\\'):
                return self.toggle_slide()
            if ch.lower() in PIANO:
                return self.put_note(self.ed.octave() * 12 + PIANO[ch.lower()])
        elif self.part == 1:
            if ks == 'Return' or ch.lower() == 'i':
                return self.set_parts(inst=self.ed.instrument_for(self.ch))
        else:
            if ch and ch.lower() in '0123456789abcdef':
                return self.set_parts(vol=int(ch, 16))
            if ch == '.':
                return self.set_parts(vol=None)
        return False

    # ---- edits
    def changed(self):
        self.find_problems()
        self.save_state()
        self.redraw()
        self.ed.cursor_moved()

    def checkpoint(self):
        self.app.hist.checkpoint(self.t)

    def advance(self):
        step = self.ed.step()
        self.row = max(0, min(len(self.t['rows']) - 1, self.row + step))
        self.show_cursor()

    def put_cell(self, text):
        if self.t['rows'][self.row][self.ch] != text:
            self.checkpoint()
            self.t['rows'][self.row][self.ch] = text
            self.changed()
        self.advance()
        return True

    def put_note(self, n):
        n = max(0, min(NOTE_MAX, n))
        inst = self.ed.instrument_for(self.ch)
        self.put_cell(cell_text(('note', n, inst, None)))
        x = self.app.proj.instrument(inst) if inst else None
        if x is not None:
            self.app.play_note(x, n, self.ch, seconds=min(0.5, note_seconds(x)))
        return True

    def toggle_slide(self):
        c = cell_or_none(self.t['rows'][self.row][self.ch])
        if not c or c[0] == 'off':
            self.app.status('A slide is a note: put a note there first')
            return True
        new = ('slide', c[1]) if c[0] == 'note' else ('note', c[1], self.ed.instrument_for(self.ch), None)
        self.checkpoint()
        self.t['rows'][self.row][self.ch] = cell_text(new)
        self.changed()
        return True

    def set_parts(self, **parts):
        """Sets the instrument or volume of the selected notes, or of the cursor's note."""
        box = self.sel_box() or (self.row, self.ch, self.row, self.ch)
        cells = [(r, ch) for r in range(box[0], box[2] + 1) for ch in range(box[1], box[3] + 1)]
        new = {}
        for r, ch in cells:
            c = cell_or_none(self.t['rows'][r][ch])
            if c and c[0] == 'note':
                inst = parts['inst'] if 'inst' in parts else c[2]
                vol = parts['vol'] if 'vol' in parts else c[3]
                new[(r, ch)] = cell_text(('note', c[1], inst, vol))
        if not new:
            self.app.status('The %s goes with a note: put a note there first' % ('instrument' if 'inst' in parts else 'volume'))
            return True
        self.apply(new)
        if not self.sel:
            self.advance()
        return True

    def apply(self, new):
        """new: {(row, channel): text}. One undo step; nothing when nothing changes."""
        rows = self.t['rows']
        new = {k: v for k, v in new.items() if rows[k[0]][k[1]] != v}
        if not new:
            return
        self.checkpoint()
        for (r, ch), v in new.items():
            rows[r][ch] = v
        self.changed()

    def clear(self):
        box = self.sel_box()
        if box is None:
            c = cell_or_none(self.t['rows'][self.row][self.ch])
            if c and c[0] == 'note' and self.part:
                return self.set_parts(**({'inst': None} if self.part == 1 else {'vol': None}))
            box = (self.row, self.ch, self.row, self.ch)
        self.apply({(r, ch): '' for r in range(box[0], box[2] + 1) for ch in range(box[1], box[3] + 1)})
        return True

    def copy(self):
        box = self.sel_box() or (self.row, self.ch, self.row, self.ch)
        self.app.clip = [[self.t['rows'][r][ch] for ch in range(box[1], box[3] + 1)] for r in range(box[0], box[2] + 1)]
        self.app.status('Copied %d row%s x %d channel%s' % (len(self.app.clip), '' if len(self.app.clip) == 1 else 's',
                                                             len(self.app.clip[0]), '' if len(self.app.clip[0]) == 1 else 's'))
        return True

    def paste(self):
        clip = self.app.clip
        if not clip:
            self.app.status('Nothing copied yet')
            return True
        rows = self.t['rows']
        new = {}
        for dr, line in enumerate(clip):
            for dc, v in enumerate(line):
                r, ch = self.row + dr, self.ch + dc
                if r < len(rows) and ch < 4:
                    new[(r, ch)] = v
        self.apply(new)
        self.sel = ((self.row, self.ch), (min(len(rows) - 1, self.row + len(clip) - 1), min(3, self.ch + len(clip[0]) - 1)))
        self.redraw()
        return True

    def transpose(self, d):
        box = self.sel_box() or (self.row, self.ch, self.row, self.ch)
        new = {}
        for r in range(box[0], box[2] + 1):
            for ch in range(box[1], box[3] + 1):
                c = cell_or_none(self.t['rows'][r][ch])
                if c and c[0] in ('note', 'slide') and 0 <= c[1] + d <= NOTE_MAX:
                    new[(r, ch)] = cell_text((c[0], c[1] + d) + tuple(c[2:]))
        self.apply(new)
        return True

    def insert_row(self):
        rows = self.t['rows']
        if len(rows) >= MAX_ROWS:
            self.app.status('A tune has at most %d rows' % MAX_ROWS)
            return True
        self.checkpoint()
        rows.insert(self.row, list(BLANK_ROW))
        if self.t.get('loop') is not None and self.t['loop'] > self.row:
            self.t['loop'] += 1
        self.changed()
        self.ed.rows_changed()
        return True

    def delete_row(self):
        rows = self.t['rows']
        if len(rows) <= 1:
            return True
        self.checkpoint()
        del rows[self.row]
        if self.t.get('loop') is not None:
            if self.t['loop'] > self.row:
                self.t['loop'] -= 1
            self.t['loop'] = min(self.t['loop'], len(rows) - 1)
        self.row = min(self.row, len(rows) - 1)
        self.changed()
        self.ed.rows_changed()
        return True

    # ---- typing a cell as text
    def edit_text(self):
        self.commit_entry()
        vis = self.visible()
        if not self.top <= self.row < self.top + vis:
            self.show_cursor()
        y = self.lh + 2 + (self.row - self.top) * self.lh
        self.entry = tk.Entry(self, font=self.font, width=self.CELL + 2, bg='#ffffff', relief='flat')
        self.entry.insert(0, self.t['rows'][self.row][self.ch])
        self.entry.select_range(0, 'end')
        self.create_window(self.cell_x(self.ch) - 2, y, window=self.entry, anchor='nw', tags='entry')
        self.entry.focus_set()
        self.entry.bind('<Return>', lambda e: (self.commit_entry(), 'break')[1])
        self.entry.bind('<Escape>', lambda e: (self.cancel_entry(), 'break')[1])
        self.entry.bind('<FocusOut>', lambda e: self.commit_entry())

    def cancel_entry(self):
        if self.entry is not None:
            self.entry.destroy()
            self.entry = None
            self.delete('entry')
            self.focus_set()

    def commit_entry(self):
        if self.entry is None:
            return
        text = self.entry.get().strip()
        try:
            c = parse_cell(text)
        except ValueError as ex:
            self.app.status('Not changed: %s' % ex)
            self.bell()
            self.cancel_entry()
            return
        self.cancel_entry()
        self.apply({(self.row, self.ch): cell_text(c)})

    # ---- playing
    def set_playrow(self, r):
        if r == self.playrow:
            return
        self.playrow = r
        if r is not None and self.ed.follow.get() and not self.top <= r < self.top + self.visible():
            self.top = max(0, r - 2)
        self.redraw()


