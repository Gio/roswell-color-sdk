        Field(h, self.w['name'], lambda v: rename_wave(app, i, v), width=16).pack(side='left', padx=z(8))
        ops.buttons(h, i).pack(side='left')
        ttk.Label(self, text='32 samples of 0..15, played left to right, round and round, by the wave channel (CH3). '
                  'Click or drag to draw.').pack(anchor='w', pady=(z(8), z(6)))
        self.cw, self.ch = z(22), z(16)
        self.cv = tk.Canvas(self, width=32 * self.cw + 1, height=16 * self.ch + 1, bg=WAVE_BG, highlightthickness=0)
        self.cv.pack(anchor='w')
