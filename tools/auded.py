def open_project(folder):
    """The sound project in folder: (Project, False), or (Project, True) when there was none and a blank one
    was made, the folder too if it did not exist."""
    folder = Path(folder)
    if (folder / 'sound.json').exists():
        return Project(folder), False
    if folder.exists() and not folder.is_dir():
        raise NotADirectoryError('%s is a file, not a folder' % folder)
    return Project.create(folder), True


