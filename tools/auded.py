def cid(s):
    """C identifier part from a name: offPink -> OFF_PINK."""
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', s)
    return re.sub(r'^_|_$', '', re.sub(r'[^A-Za-z0-9]+', '_', s)).upper()


