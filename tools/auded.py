    def folder(self):
        t = self.var.get().strip().strip('"')
        if not t:
            return None
        p = Path(os.path.expanduser(t))
        return p if p.is_absolute() else Path.cwd() / p

    def describe(self):
        """Says what Open will do with the folder typed."""
        p = self.folder()
        if p is None:
            text = 'Type a folder, or Browse to one.'
        elif (p / 'sound.json').exists():
            text = 'Opens the sound project there.'
        elif p.exists() and not p.is_dir():
            text = 'That is a file, not a folder.'
        elif p.exists():
            text = 'There is no sound project there yet: Open makes a blank one in it.'
        else:
            text = 'That folder does not exist yet: Open makes it, with a blank sound project in it.'
        self.note.config(text=text)
        return text

    def browse(self):
        from tkinter import filedialog
        p = self.folder()
        start = p if p and p.is_dir() else p.parent if p and p.parent.is_dir() else Path.cwd()
        d = filedialog.askdirectory(parent=self.w, initialdir=str(start), title='Sound folder', mustexist=False)
        if d:
            self.var.set(str(Path(d)))

    def ok(self):
        p = self.folder()
        if p is None or (p.exists() and not p.is_dir()):
            self.w.bell()
            return
        self.result = p
        self.w.destroy()

    def cancel(self):
        self.w.destroy()

    def wait(self):
        self.w.wait_window()
        return self.result


