class Ops:
    """New / duplicate / delete / move / rename for a list of named things (waves, instruments, songs,
    sound effects). valid(name) says why a name cannot be used, or None; uses(i) what would miss item i
    if it went; new items are called new_<base>."""

    def __init__(self, app, items, docs, key, loc_of, back, make, what, valid=None, keep=0, uses=None, base=None):
        self.app, self.items, self.docs, self.key, self.loc_of, self.back, self.make, self.what = \
            app, items, docs, key, loc_of, back, make, what
        self.valid, self.keep = valid or (lambda name: None), keep
        self.uses, self.base = uses or (lambda i: ''), base or what

    def unique(self, base):
        taken = {cid(x[self.key]) for x in self.items}
        name, k = base, 2
        while cid(name) in taken:
            name, k = '%s_%d' % (base, k), k + 1
        return name

    def buttons(self, parent, i):
        f = ttk.Frame(parent)
        for txt, fn in (('New', lambda: self.new(i + 1)), ('Duplicate', lambda: self.dup(i)), ('Delete', lambda: self.delete(i)),
                        ('Move up', lambda: self.move(i, -1)), ('Move down', lambda: self.move(i, 1))):
            ttk.Button(f, text=txt, command=fn).pack(side='left', padx=1)
        return f

    def dup(self, i):
        item = copy.deepcopy(self.items[i])
        item[self.key] = self.unique(self.items[i][self.key] + '_copy')
        self.app.hist.checkpoint(*self.docs)
        self.items.insert(i + 1, item)
        self.app.goto(self.loc_of(i + 1))

    def move(self, i, d):
        j = i + d
        if 0 <= j < len(self.items):
            self.app.hist.checkpoint(*self.docs)
            self.items[i], self.items[j] = self.items[j], self.items[i]
            self.app.goto(self.loc_of(j))

    def rename(self, i, v, extra=()):
        v = v.strip()
        if not NAME_RE.match(v):
            return 'A name is letters, digits and _, and starts with a letter.'
        if any(cid(x[self.key]) == cid(v) for j, x in enumerate(self.items) if j != i):
            return 'Another %s already has that name (or one that is the same in C).' % self.what
        if self.valid(v):
            return self.valid(v)
        self.app.hist.checkpoint(*self.docs, self.items[i], *extra)   # the item too: a list snapshot is shallow
        self.items[i][self.key] = v
        self.app.rebuild_tree()
        return None

    def new(self, at=None):
        at = len(self.items) if at is None else at
        self.app.hist.checkpoint(*self.docs)
        self.items.insert(at, self.make(self.unique('new_' + self.base)))
        self.app.goto(self.loc_of(at))

    def delete(self, i):
        if len(self.items) <= self.keep:
            messagebox.showinfo('Delete', 'The last %s cannot be deleted.' % self.what)
            return
        u = self.uses(i)
        if messagebox.askyesno('Delete', 'Delete %s %s?%s\n\n(Edit > Undo brings it back.)' % (
                self.what, self.items[i][self.key], '\n\n' + u if u else '')):
            self.app.hist.checkpoint(*self.docs)
            del self.items[i]
            self.app.goto(self.back)


