class Player:
    """Plays samples on the computer's speakers, one sound at a time. It writes them to a .wav file and
    hands that to the system: winsound on Windows, afplay on macOS, aplay / paplay elsewhere."""

    def __init__(self):
        self.dir = Path(tempfile.mkdtemp(prefix='auded_'))
        self.n, self.proc, self.started, self.length, self.enabled = 0, None, 0.0, 0.0, True

    def play(self, samples):
        """Returns None, or why it could not play."""
        self.stop()
        self.n += 1
        path = self.dir / ('play%d.wav' % self.n)
        write_wav(path, samples)
        for f in self.dir.glob('play*.wav'):
            if f != path:
                try:
                    f.unlink()
                except OSError:
                    pass
        self.started, self.length = time.monotonic(), len(samples) / float(RATE)
        if not self.enabled:
            return None
        try:
            if sys.platform == 'win32':
                import winsound
                winsound.PlaySound(str(path), winsound.SND_FILENAME | winsound.SND_ASYNC | winsound.SND_NODEFAULT)
                return None
            cmds = [['afplay']] if sys.platform == 'darwin' else [['aplay', '-q'], ['paplay'], ['ffplay', '-nodisp', '-autoexit', '-loglevel', 'quiet']]
            for cmd in cmds:
                try:
                    self.proc = subprocess.Popen(cmd + [str(path)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    return None
                except FileNotFoundError:
                    continue
            return 'no program to play sound with (tried %s)' % ', '.join(c[0] for c in cmds)
        except Exception as ex:     # a sound device that is missing or busy should not stop the editor
            self.started = 0.0
            return str(ex)

    def elapsed(self):
        """Seconds since the sound started, or None when nothing is playing."""
        if not self.started:
            return None
        t = time.monotonic() - self.started
        return t if t < self.length else None

    def stop(self):
        if self.started and self.enabled and sys.platform == 'win32':
            import winsound
            winsound.PlaySound(None, 0)
        if self.proc is not None:
            self.proc.terminate()
            self.proc = None
        self.started = 0.0

    def close(self):
        self.stop()
        import shutil
        shutil.rmtree(self.dir, ignore_errors=True)


